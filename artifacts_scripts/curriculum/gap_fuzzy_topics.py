"""Fuzzy/soft topic membership — increment 1 (non-invasive prototype).

Given a built curriculum run-dir, compute ONE-SHOT soft responsibilities r_{i,k}
of each selected work to each topic (softmax over topic centroids, temperature
set by target perplexity — the validated multi-cluster-softmax form, see
docs/backlog/curriculum-fuzzy-soft-topic-membership.md). Reports, per topic, the
HARD cluster size vs the SOFT mass-weighted size and its effective sample size
(ESS), and — for the most degenerate hard topic — its top soft members.

Purpose: validate the core fuzzy claim before pipeline integration — does soft
membership give a degenerate ~1-work chapter (the Neuromorphic/Color-Image debris
source) a real population, dissolving it? This is the curriculum-side analogue of
the gap-side `gap_softmax_reassign.py` Phase-1 experiment.

This does NOT modify the pipeline; it reads the run-dir + cloud and reports.
Centroid-kernel softmax is a simplification of the per-member-normalized form;
the absorbing-walk (citation-aware) variant is the planned comparison arm.

Example:
  python -m artifacts_scripts.curriculum.gap_fuzzy_topics \\
      --run-dir artifacts/curriculum/neuromorphic_trackA_sem --field 17 \\
      --out docs/curriculum_eval_examples/neuromorphic_photonics/fuzzy_topics_probe.md
"""
from __future__ import annotations

import argparse
import json
import shlex
import sys
from pathlib import Path

import numpy as np
from hydra.utils import instantiate
from omegaconf import OmegaConf
from scipy.special import softmax

from artifacts_scripts.curriculum.config import CurriculumConfig
from bookgap.util import LOGGER, setup_logging

_MODULE = "artifacts_scripts.curriculum.gap_fuzzy_topics"


def _provenance() -> str:
    cmd = f"python -m {_MODULE} " + " ".join(shlex.quote(a) for a in sys.argv[1:])
    return ("\n\n---\n"
            f"*Generated by `{cmd}`*  \n"
            "*Regenerate with the command above; do not edit by hand.*\n")


def _unit(x: np.ndarray) -> np.ndarray:
    return x / np.maximum(np.linalg.norm(x, axis=-1, keepdims=True), 1e-12)


def soft_responsibilities(E_unit, C_unit, perplexity):
    """One-shot soft responsibilities R (n_works x n_topics) of each work to each
    topic: softmax over cosine-to-centroid, temperature set by target perplexity.

    E_unit / C_unit must be unit-normalized (works, centroids). Returns (R, tau).
    Anti-diffusion is structural: fixed centroids + the softmax simplex constraint
    (Σ_k R_ik = 1), one-shot (no iteration — iteration diffuses to uniform, see
    docs/dead_ends/.../full-data-soft-mixture-degenerate-bootstrap.md)."""
    sims = E_unit @ C_unit.T
    tau = _calibrate_tau(sims, perplexity)
    return softmax(sims / tau, axis=1), tau


def _calibrate_tau(sims: np.ndarray, target_perplexity: float) -> float:
    """Bisect the softmax temperature so the mean per-work perplexity ≈ target.

    Higher tau -> flatter responsibilities -> higher perplexity (toward K). The
    t-SNE trick: pick the softness from a target effective #-topics-per-work
    rather than a hand-tuned tau."""
    def mean_perp(tau: float) -> float:
        r = softmax(sims / tau, axis=1)
        h = -np.sum(np.where(r > 0, r * np.log(r), 0.0), axis=1)
        return float(np.mean(np.exp(h)))

    lo, hi = 1e-3, 10.0
    for _ in range(40):
        mid = (lo + hi) / 2
        if mean_perp(mid) < target_perplexity:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--run-dir", required=True, type=Path)
    ap.add_argument("--field", default="17", help="OpenAlex field id for the cloud scope (CS=17).")
    ap.add_argument("--perplexity", type=float, default=1.5,
                    help="target mean topics-per-work (softmax softness; t-SNE-style).")
    ap.add_argument("--top-members", type=int, default=12,
                    help="how many top soft members to list for the most-degenerate hard topic.")
    ap.add_argument("--out", default=None, type=Path, help="optional markdown report path.")
    args = ap.parse_args()
    setup_logging(log_name="fuzzy_topics", log_level="INFO", include_time=False)

    rd = args.run_dir
    cfg = OmegaConf.structured(CurriculumConfig())
    cfg.experiment.cloud.filter_pair.pre.field = str(args.field)
    cloud = instantiate(cfg.experiment.cloud)
    work_ids = cloud.work_ids()
    emb_all = np.asarray(cloud.embeddings(), dtype=np.float32)
    titles = cloud.work_titles()
    id2idx = {w: i for i, w in enumerate(work_ids)}

    fids = json.loads((rd / "filtered_work_ids.json").read_text())
    filt = np.array([id2idx[w] for w in fids], dtype=np.intp)
    E = _unit(emb_all[filt])                                  # (n, d) selected works
    masses = np.load(rd / "leaf_masses.npy").astype(np.float64)  # (n,) aligned with fids
    filt_titles = [titles[i] for i in filt]
    pos = {w: i for i, w in enumerate(fids)}                  # work_id -> filtered position

    twi = json.loads((rd / "topic_work_ids.json").read_text())
    tkeys = sorted(twi, key=lambda k: int(k))
    n_topics = len(tkeys)
    # Centroid per topic = mass-weighted mean embedding of its hard members.
    C = np.zeros((n_topics, E.shape[1]), dtype=np.float32)
    hard_sizes = []
    for ki, k in enumerate(tkeys):
        midx = [pos[w] for w in twi[k] if w in pos]
        hard_sizes.append(len(midx))
        w = masses[midx]
        C[ki] = np.average(E[midx], axis=0, weights=w if w.sum() > 0 else None)
    C = _unit(C)

    R, tau = soft_responsibilities(E, C, args.perplexity)    # (n, K) responsibilities
    LOGGER.info("tau=%.4f for target perplexity=%.2f (mean topics/work)", tau, args.perplexity)

    mr = masses[:, None] * R                                  # (n, K) mass x responsibility
    soft_size = mr.sum(axis=0)                                # Σ_i mass_i r_ik
    ess = np.where(soft_size > 0, soft_size**2 / np.maximum((mr**2).sum(axis=0), 1e-30), 0.0)
    total_mass = masses.sum()

    lines = [f"# Fuzzy soft-membership probe — {rd.name}", "",
             f"One-shot softmax responsibilities over {n_topics} topic centroids; "
             f"tau={tau:.3f} calibrated to target perplexity {args.perplexity} "
             f"(mean topics/work). Total mass = {total_mass:.4f}.", "",
             "| topic | hard size | soft size (Σ mass·r) | soft ESS (works) |",
             "| :---: | :---: | :---: | :---: |"]
    for ki, k in enumerate(tkeys):
        lines.append(f"| {k} | {hard_sizes[ki]} | {soft_size[ki]:.4f} | {ess[ki]:.1f} |")

    deg = int(np.argmin(hard_sizes))
    lines += ["", f"## Most degenerate hard topic: {tkeys[deg]} (hard size {hard_sizes[deg]}, "
              f"soft ESS {ess[deg]:.1f})", "",
              "Top soft members by responsibility (would populate the chapter under soft "
              "membership, vs the single hard member):", ""]
    order = np.argsort(R[:, deg])[::-1][:args.top_members]
    for i in order:
        lines.append(f"- r={R[i, deg]:.3f}  ·  {filt_titles[i][:90]}")

    report = "\n".join(lines)
    print(report)
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(report + _provenance())
        print(f"\nwrote {args.out}")


if __name__ == "__main__":
    main()

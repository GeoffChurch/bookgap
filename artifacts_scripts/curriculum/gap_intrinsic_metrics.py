"""Intrinsic (book-free) curriculum-quality metrics — head-to-head for two curricula.

Motivated by the ceiling test: our organization is a *valid alternative* cut of the
book's content (ARI ~0.18, unimproved by ideal targets), so "match the book" is the
wrong goal. These measure curriculum quality directly, with NO gold standard, and are
computed identically for both curricula so a focused frontier curriculum can win.

Metrics (all on the curriculum's own works + sparse citation subgraph + a corpus sample):
  - silhouette       : embedding silhouette of the chapter partition (coherence + separation)
  - prereq_consist   : fraction of cross-chapter citations whose CITED work is in an
                       earlier-or-same chapter (a valid prerequisite order cites backward)
  - recency_year     : mass-unweighted mean publication year (frontier skew)
  - kw_distinct      : 1 − mean between-chapter keyword-set Jaccard (label separation)
  - kw_gap_lift      : α-weighted mean log-lift PMI(keyword; gap) vs a corpus-sample
                       background — do the keywords LOCATE the gap (grounded anti-debris)

Example:
  python -m artifacts_scripts.curriculum.gap_intrinsic_metrics \\
      --run-a artifacts/curriculum/neuromorphic_trackA_sem \\
      --run-b artifacts/curriculum/neuromorphic_trackB \\
      --gap-json artifacts/book_gaps/neuromorphic_gap.json --field 17 \\
      --out docs/curriculum_eval_examples/neuromorphic_photonics/intrinsic_metrics.md
"""
from __future__ import annotations

import argparse
import json
import re
import shlex
import sys
from pathlib import Path

import numpy as np
from hydra.utils import instantiate
from omegaconf import OmegaConf

from artifacts_scripts.curriculum.config import CurriculumConfig
from artifacts_scripts.curriculum.eval_book_judge import load_book_outline
from artifacts_scripts.curriculum.gap_fuzzy_topics import _unit
from bookgap.util import LOGGER, setup_logging

_MODULE = "artifacts_scripts.curriculum.gap_intrinsic_metrics"
_TOK = re.compile(r"[a-z0-9]+")


def _provenance() -> str:
    cmd = f"python -m {_MODULE} " + " ".join(shlex.quote(a) for a in sys.argv[1:])
    return f"\n\n---\n*Generated by `{cmd}`*  \n*Regenerate with the command above; do not edit by hand.*\n"


def _termset(text: str) -> set:
    t = _TOK.findall(text.lower())
    return set(t) | {f"{t[i]} {t[i+1]}" for i in range(len(t) - 1)}  # unigrams + bigrams


def _silhouette(E, labels):
    """Embedding silhouette via per-chapter centroids (cheap; cosine distance)."""
    ks = sorted(set(labels))
    C = {k: _unit(E[labels == k].mean(0, keepdims=True))[0] for k in ks}
    sil = []
    for i in range(len(E)):
        d = {k: 1.0 - float(E[i] @ C[k]) for k in ks}
        a = d[labels[i]]
        b = min(v for k, v in d.items() if k != labels[i]) if len(ks) > 1 else a
        sil.append((b - a) / max(a, b, 1e-9))
    return float(np.mean(sil))


def _prereq_consistency(adj_sub, labels, order):
    """Fraction of cross-chapter citation edges (u cites v) whose cited work v is in an
    earlier-or-same chapter than u (order[chap(v)] <= order[chap(u)])."""
    adj = adj_sub.tocoo()
    good = tot = 0
    for u, v in zip(adj.row, adj.col):
        cu, cv = labels[u], labels[v]
        if cu == cv:
            continue
        tot += 1
        if order[cv] <= order[cu]:
            good += 1
    return good / tot if tot else float("nan"), tot


def _metrics_for(run_dir, cloud, id2idx, E_all, dates, abstracts, gap_ids, bg_idx, field):
    bo = load_book_outline(run_dir)
    twi = json.loads((run_dir / "topic_work_ids.json").read_text())
    ch_keys = sorted(twi, key=lambda x: int(x))
    # per-work chapter label (over works present in the cloud), + order = chapter index
    wlab, widx = [], []
    for ci, k in enumerate(ch_keys):
        for w in twi[k]:
            if w in id2idx:
                wlab.append(ci); widx.append(id2idx[w])
    wlab = np.array(wlab); widx = np.array(widx)
    E = _unit(E_all[widx])
    order = {ci: ci for ci in range(len(ch_keys))}

    sil = _silhouette(E, wlab)
    adj_sub = cloud.citation_graph(False)[widx][:, widx]
    prereq, n_edges = _prereq_consistency(adj_sub, wlab, order)
    years = [int(dates[i][:4]) for i in widx if dates[i] and dates[i][:4].isdigit()]
    recency = float(np.mean(years)) if years else float("nan")

    # keyword distinctiveness (between-chapter keyword-set Jaccard)
    kw = [set(c.keywords) for c in bo.chapters]
    jac = [len(kw[i] & kw[j]) / len(kw[i] | kw[j]) for i in range(len(kw)) for j in range(i + 1, len(kw)) if kw[i] | kw[j]]
    kw_distinct = 1.0 - float(np.mean(jac)) if jac else float("nan")

    # keyword->gap lift: PMI(keyword; gap) vs corpus-sample background, alpha-weighted
    all_kw = {}
    for c in bo.chapters:
        for r, w in enumerate(c.keywords):
            all_kw[w] = all_kw.get(w, 0.0) + 1.0 / (r + 1)   # alpha = rank-decayed weight
    gap_sets = [_termset(abstracts[id2idx[a]]) for a in gap_ids if a in id2idx]
    bg_sets = [_termset(abstracts[i]) for i in bg_idx]
    ng, nb, eps = len(gap_sets), len(bg_sets), 0.5
    lifts = []
    for w, a in all_kw.items():
        term = w.replace("_", " ")
        pg = (sum(term in s for s in gap_sets) + eps) / (ng + eps)
        pb = (sum(term in s for s in bg_sets) + eps) / (nb + eps)
        lifts.append((a, float(np.log(pg / pb))))
    wsum = sum(a for a, _ in lifts)
    kw_gap_pmi = sum(a * l for a, l in lifts) / wsum if wsum else float("nan")

    return {"chapters": len(ch_keys), "n_works": len(widx), "silhouette": sil,
            "prereq_consist": prereq, "n_cross_edges": n_edges, "recency_year": recency,
            "kw_distinct": kw_distinct, "kw_gap_pmi": kw_gap_pmi}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--run-a", required=True, type=Path)
    ap.add_argument("--run-b", required=True, type=Path)
    ap.add_argument("--gap-json", required=True, type=Path)
    ap.add_argument("--field", default="17")
    ap.add_argument("--bg-sample", type=int, default=40000)
    ap.add_argument("--out", default=None, type=Path)
    args = ap.parse_args()
    setup_logging(log_name="intrinsic", log_level="INFO", include_time=False)

    cfg = OmegaConf.structured(CurriculumConfig())
    cfg.experiment.cloud.filter_pair.pre.field = str(args.field)
    cloud = instantiate(cfg.experiment.cloud)
    wid = cloud.work_ids(); id2idx = {w: i for i, w in enumerate(wid)}
    E_all = np.asarray(cloud.embeddings(), dtype=np.float32)
    dates = cloud.work_publication_dates(); abstracts = cloud.work_abstracts()

    rec = json.loads(args.gap_json.read_text()); bk = rec.get("book", rec)
    gap_ids = bk["gap_article_ids"]
    rng = np.random.default_rng(0)
    bg_idx = rng.choice(len(wid), min(args.bg_sample, len(wid)), replace=False)

    mA = _metrics_for(args.run_a, cloud, id2idx, E_all, dates, abstracts, gap_ids, bg_idx, args.field)
    mB = _metrics_for(args.run_b, cloud, id2idx, E_all, dates, abstracts, gap_ids, bg_idx, args.field)

    keys = ["chapters", "n_works", "silhouette", "prereq_consist", "recency_year", "kw_distinct", "kw_gap_pmi"]
    lines = [f"# Intrinsic metrics — {args.run_a.name} (A) vs {args.run_b.name} (B)", "",
             f"Gap seed: {len(gap_ids)} works · corpus background sample: {len(bg_idx)} · "
             "higher is better for silhouette / prereq_consist / kw_distinct / kw_gap_pmi; "
             "recency = mean pub year (higher = more frontier).", "",
             "| metric | A (ours) | B (book ToC) |", "| :-- | :--: | :--: |"]
    for k in keys:
        va, vb = mA[k], mB[k]
        lines.append(f"| {k} | {va:.3f} | {vb:.3f} |" if isinstance(va, float) else f"| {k} | {va} | {vb} |")
    report = "\n".join(lines)
    print(report)
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(report + _provenance())
        print(f"\nwrote {args.out}")


if __name__ == "__main__":
    main()

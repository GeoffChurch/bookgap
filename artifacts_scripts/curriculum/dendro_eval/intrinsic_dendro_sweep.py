"""Intrinsic dendrogram-quality sweep on one ingested field corpus.

Ranks the repo's hierarchical-clustering constructions by tree-quality metrics
that need NO ground-truth labels. This is the "fast first number" + plumbing
validation for a larger dendrogram-optimization effort: it answers whether the
constructions even *separate* on intrinsic metrics (i.e. whether intrinsic
tree quality is a usable optimization signal at all).

Corpus
------
Reads RAW work embeddings straight from the per-(corpus, embedder) Parquet
store (``bookgap.cloud.read_embeddings_store``), bypassing the full ``Cloud``
construction (which would re-resolve taxonomy + fetch the corpus). The default
scope is NLP topic T10181, GIST-small (384d) — corpus fingerprint
``b82fee73eb29324b`` / embedder fingerprint ``6bcf5b5e02946b7e``. These are
reconstructed deterministically from ``Filter(topic=..., work_types=...)`` via
``_corpus_fingerprint`` so the script self-documents which scope it loads.
GIST-small already L2-normalizes at encode time; we ``_unit`` anyway (idempotent,
numerically guarded) to match the canonical curriculum clustering pattern
(``build_curriculum.py`` -> ``bisecting_kmeans_linkage`` on unit vectors ~= cosine).

Constructions (all embedding-only; citation-fusion deferred)
------------------------------------------------------------
1. ``weighted_bisecting_kmeans`` — the repo default recursive-binary-kmeans
   builder (``scalable_clustering.bisecting_kmeans_linkage``, unweighted here).
2. ``scipy_ward`` — ``scipy.cluster.hierarchy.linkage(X, method="ward")``.
3. ``scipy_average_cosine`` — ``linkage(X, method="average", metric="cosine")``.

All three are built on the SAME ~2,500-point sub-subsample so the O(N^2)
cophenetic / Dasgupta metrics are directly comparable. (Bisecting-kmeans is
ALSO sanity-built on the larger ~18k tree-subsample to confirm it runs at the
scale the curriculum pipeline uses, but metrics are reported on the common 2.5k
set.)

Metrics
-------
* Cophenetic correlation (higher better) — Pearson corr between tree (cophenetic)
  distances and original pairwise distances. The bisecting-kmeans leaf IDs are
  assigned in traversal order, NOT original row order, so we remap X into leaf
  order via ``leaf_cluster_assignments`` (a permutation when min_cluster_size=1)
  before pdist. scipy linkages already index leaves as X rows.
* Dasgupta cost (lower better), via the merge-based formula
  cost = sum over internal merges of |L u R| * sum_{i in L, j in R} w_ij,
  with w_ij = max(cos(i,j), 0). Reported (a) normalized by (n * sum_all_wij) and
  (b) as a ratio to a RANDOM binary merge tree's cost on the same points +
  similarities (ratio < 1 == better than random).
* Silhouette of a ~50-cluster flat cut (``fcluster``) — familiar cross-check.

Regenerate (do not edit generated JSON by hand):

  .conda/bin/python -m artifacts_scripts.curriculum.dendro_eval.intrinsic_dendro_sweep
"""
from __future__ import annotations

import argparse
import json
import shlex
import sys
import time
from pathlib import Path

import numpy as np
from numpy.typing import NDArray
from scipy.cluster.hierarchy import cophenet, fcluster, linkage
from scipy.spatial.distance import pdist
from sklearn.metrics import silhouette_score

from bookgap.cloud import _corpus_fingerprint, _embeddings_store_path, read_embeddings_store
from bookgap.configs.embedder.embedder_config import SentenceTransformerEmbedderConfig
from bookgap.util import Filter, WorkType
from artifacts_scripts.curriculum.scalable_clustering import bisecting_kmeans_linkage

_MODULE = "artifacts_scripts.curriculum.dendro_eval.intrinsic_dendro_sweep"
_HERE = Path(__file__).resolve().parent

# Standard 4 work-types used across the project's ingested corpora.
_WT4 = (
    WorkType.BOOK.value,
    WorkType.ARTICLE.value,
    WorkType.BOOK_CHAPTER.value,
    WorkType.PREPRINT.value,
)


def _provenance() -> str:
    cmd = f"python -m {_MODULE} " + " ".join(shlex.quote(a) for a in sys.argv[1:])
    return (
        f"Generated by `{cmd}`. "
        "Regenerate with the command above; do not edit by hand."
    )


def _unit(x: NDArray) -> NDArray:
    """L2-normalize rows (matches build_curriculum.py's _unit; idempotent here)."""
    x = np.ascontiguousarray(x, dtype=np.float32)
    return x / np.maximum(np.linalg.norm(x, axis=1, keepdims=True), 1e-12)


def _load_scope_embeddings(topic: str) -> tuple[NDArray, str, str]:
    """Load raw embeddings for a topic-scoped GIST-small corpus.

    Returns (embeddings, corpus_fingerprint, embedder_fingerprint).
    """
    filt = Filter(topic=topic, work_types=_WT4)
    corpus_fp = _corpus_fingerprint(filt, None)
    emb_cfg = SentenceTransformerEmbedderConfig()  # GIST-small default
    path = _embeddings_store_path(corpus_fp, emb_cfg)
    if not path.exists():
        raise FileNotFoundError(
            f"No embeddings store for topic={topic} GIST-small at {path}. "
            "Reconstructed corpus_fp=" + corpus_fp
        )
    E = read_embeddings_store(path)
    return E, corpus_fp, path.parent.name


# --------------------------------------------------------------------------
# Dasgupta cost (merge-based)
# --------------------------------------------------------------------------
def _cosine_sim_pos(X: NDArray) -> NDArray:
    """Full (n,n) cosine similarity with negatives clipped to 0. X assumed unit-norm."""
    S = X @ X.T
    np.clip(S, 0.0, None, out=S)
    return S


def _dasgupta_cost_from_linkage(Z: NDArray, S: NDArray) -> float:
    """Dasgupta cost by walking a scipy linkage bottom-up.

    cost = sum over internal merges of |L u R| * sum_{i in L, j in R} S[i,j],
    where S[i,j] is the (>=0) similarity and leaf k of Z indexes row/col k of S.

    Tracks each node's member-index list and accumulates the cross-block
    similarity mass at each merge. O(sum of block products) similarity lookups;
    fine for n ~ 2.5k.
    """
    n = S.shape[0]
    members: dict[int, list[int]] = {i: [i] for i in range(n)}
    cost = 0.0
    for m, row in enumerate(Z):
        a, b = int(row[0]), int(row[1])
        la, lb = members[a], members[b]
        # cross-block similarity mass between the two merging subtrees
        block = S[np.ix_(la, lb)]
        cost += (len(la) + len(lb)) * float(block.sum())
        merged = la + lb
        members[n + m] = merged
        # free children to bound memory
        del members[a]
        del members[b]
    return cost


def _dasgupta_cost_random(S: NDArray, rng: np.random.Generator) -> float:
    """Dasgupta cost of a RANDOM binary merge tree over the same points.

    Repeatedly pick two active nodes uniformly at random and merge; same
    accumulation as the linkage walk. Gives a baseline so a method's cost can be
    reported as a ratio (ratio < 1 == better-than-random tree structure).
    """
    n = S.shape[0]
    members: dict[int, list[int]] = {i: [i] for i in range(n)}
    active = list(range(n))
    next_id = n
    cost = 0.0
    while len(active) > 1:
        i, j = rng.choice(len(active), size=2, replace=False)
        if i > j:
            i, j = j, i
        a = active[j]
        b = active[i]
        active.pop(j)
        active.pop(i)
        la, lb = members[a], members[b]
        block = S[np.ix_(la, lb)]
        cost += (len(la) + len(lb)) * float(block.sum())
        members[next_id] = la + lb
        del members[a]
        del members[b]
        active.append(next_id)
        next_id += 1
    return cost


# --------------------------------------------------------------------------
# Per-construction evaluation
# --------------------------------------------------------------------------
def _eval_linkage(
    name: str,
    Z: NDArray,
    X_leaf: NDArray,
    S_leaf: NDArray,
    dist_condensed: NDArray,
    n_flat: int,
    rand_cost: float,
    sum_all_w: float,
) -> dict:
    """Compute all intrinsic metrics for one linkage Z whose leaves index X_leaf."""
    n = X_leaf.shape[0]
    coph_corr = float(cophenet(Z, dist_condensed)[0])
    dcost = _dasgupta_cost_from_linkage(Z, S_leaf)
    dcost_norm = dcost / (n * sum_all_w) if sum_all_w > 0 else float("nan")
    dcost_ratio = dcost / rand_cost if rand_cost > 0 else float("nan")
    labels = fcluster(Z, t=n_flat, criterion="maxclust")
    k_eff = int(len(np.unique(labels)))
    if k_eff >= 2 and k_eff < n:
        sil = float(silhouette_score(X_leaf, labels, metric="cosine"))
    else:
        sil = float("nan")
    return {
        "construction": name,
        "cophenetic_corr": coph_corr,
        "dasgupta_norm": dcost_norm,
        "dasgupta_random_ratio": dcost_ratio,
        "dasgupta_raw": dcost,
        "silhouette_cos": sil,
        "flat_k_requested": n_flat,
        "flat_k_effective": k_eff,
    }


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--topic", default="T10181", help="OpenAlex topic id (default NLP T10181)")
    ap.add_argument("--tree-n", type=int, default=18000,
                    help="subsample size for the scale sanity build of bisecting-kmeans")
    ap.add_argument("--metric-n", type=int, default=2500,
                    help="common sub-subsample size for O(N^2) metrics (all 3 trees)")
    ap.add_argument("--n-flat", type=int, default=50, help="flat-cut cluster count for silhouette")
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--out", default=str(_HERE / "intrinsic_dendro_sweep_results.json"))
    args = ap.parse_args()

    t0 = time.time()
    rng = np.random.default_rng(args.seed)

    E, corpus_fp, embedder_fp = _load_scope_embeddings(args.topic)
    N_total = E.shape[0]
    print(f"[load] topic={args.topic} corpus_fp={corpus_fp} embedder_fp={embedder_fp} "
          f"N_total={N_total} dim={E.shape[1]}")

    # --- tree-building subsample (fixed seed), then common metric sub-subsample ---
    tree_n = min(args.tree_n, N_total)
    tree_idx = rng.choice(N_total, size=tree_n, replace=False)
    tree_idx.sort()
    X_tree = _unit(E[tree_idx])  # idempotent for GIST-small; matches curriculum pattern

    metric_n = min(args.metric_n, tree_n)
    # metric points are a subset of the tree points (so the scale build and the
    # metric build operate on the same population)
    sub = rng.choice(tree_n, size=metric_n, replace=False)
    sub.sort()
    X = X_tree[sub]  # (metric_n, d) unit-norm
    n = X.shape[0]
    print(f"[subsample] tree_n={tree_n} metric_n={n} (seed={args.seed})")

    # Shared metric-space quantities (in X's native row order)
    dist_condensed = pdist(X.astype(np.float64))  # euclidean on unit vectors
    S = _cosine_sim_pos(X.astype(np.float64))     # (n,n) cosine, neg->0
    sum_all_w = float(np.triu(S, 1).sum())        # sum over i<j of w_ij
    rand_cost = float(np.mean([
        _dasgupta_cost_random(S, np.random.default_rng(args.seed + r)) for r in range(3)
    ]))
    print(f"[metric-prep] sum_all_w(i<j)={sum_all_w:.1f} random_dasgupta(mean of 3)={rand_cost:.3e}")

    results: list[dict] = []

    # --- scale sanity: bisecting-kmeans on the full tree_n (curriculum scale) ---
    t = time.time()
    _ = bisecting_kmeans_linkage(
        X_tree, min_cluster_size=1, max_depth=None, random_state=args.seed,
        use_minibatch=True, verbose=False,
    )
    print(f"[scale-sanity] bisecting_kmeans on {tree_n} pts OK in {time.time()-t:.1f}s")

    # --- 1. weighted_bisecting_kmeans on the metric points ---
    t = time.time()
    bk = bisecting_kmeans_linkage(
        X, min_cluster_size=1, max_depth=None, random_state=args.seed,
        use_minibatch=False,  # exact KMeans at n=2.5k for a faithful default-builder tree
        verbose=False,
    )
    Zbk = bk.linkage
    lca = bk.leaf_cluster_assignments  # point -> leaf_id; permutation when msc=1
    assert sorted(lca.tolist()) == list(range(n)), "leaf assignments not a permutation"
    inv = np.empty(bk.n_leaf_clusters, dtype=int)
    inv[lca] = np.arange(n)
    X_leaf_bk = X[inv]                  # X_leaf_bk[leaf_id] = X[orig point at that leaf]
    S_leaf_bk = _cosine_sim_pos(X_leaf_bk.astype(np.float64))
    dist_leaf_bk = pdist(X_leaf_bk.astype(np.float64))
    print(f"[build] weighted_bisecting_kmeans tree in {time.time()-t:.1f}s "
          f"(Z={Zbk.shape}, remapped leaves to row order)")
    results.append(_eval_linkage(
        "weighted_bisecting_kmeans", Zbk, X_leaf_bk, S_leaf_bk, dist_leaf_bk,
        args.n_flat, rand_cost, sum_all_w,
    ))

    # --- 2. scipy Ward (leaves already index X rows) ---
    t = time.time()
    Zward = linkage(X.astype(np.float64), method="ward")
    print(f"[build] scipy_ward in {time.time()-t:.1f}s")
    results.append(_eval_linkage(
        "scipy_ward", Zward, X, S, dist_condensed, args.n_flat, rand_cost, sum_all_w,
    ))

    # --- 3. scipy average-linkage, cosine metric ---
    t = time.time()
    Zavg = linkage(X.astype(np.float64), method="average", metric="cosine")
    print(f"[build] scipy_average_cosine in {time.time()-t:.1f}s")
    results.append(_eval_linkage(
        "scipy_average_cosine", Zavg, X, S, dist_condensed, args.n_flat, rand_cost, sum_all_w,
    ))

    # --- ranking table ---
    cols = [
        ("cophenetic_corr", "coph_corr", "max"),
        ("dasgupta_norm", "Dasgupta_norm", "min"),
        ("dasgupta_random_ratio", "Dasg/rand", "min"),
        ("silhouette_cos", "silh@%d" % args.n_flat, "max"),
    ]
    winners: dict[str, str] = {}
    for key, _label, direction in cols:
        vals = [(r["construction"], r[key]) for r in results if not np.isnan(r[key])]
        if not vals:
            winners[key] = "n/a"
            continue
        best = (max if direction == "max" else min)(vals, key=lambda kv: kv[1])
        winners[key] = best[0]

    name_w = max(len(r["construction"]) for r in results) + 1
    header = f"{'construction':<{name_w}}" + "".join(f"{lab:>16}" for _, lab, _ in cols)
    print("\n" + "=" * len(header))
    print("INTRINSIC DENDROGRAM-QUALITY RANKING  "
          f"(topic={args.topic}, metric_n={n}, flat_k={args.n_flat})")
    print("=" * len(header))
    print(header)
    print("-" * len(header))
    for r in results:
        line = f"{r['construction']:<{name_w}}"
        for key, _lab, _d in cols:
            v = r[key]
            line += f"{(f'{v:.4f}' if not np.isnan(v) else 'nan'):>16}"
        print(line)
    print("-" * len(header))
    print("winner per metric (coph:max, Dasgupta:min, ratio:min, silh:max):")
    for key, lab, _d in cols:
        print(f"  {lab:<16} -> {winners[key]}")

    # spread diagnostics: do methods SEPARATE on each metric?
    print("\nspread across methods (max - min):")
    for key, lab, _d in cols:
        vals = [r[key] for r in results if not np.isnan(r[key])]
        if len(vals) >= 2:
            spread = max(vals) - min(vals)
            rel = spread / (abs(np.mean(vals)) + 1e-12)
            print(f"  {lab:<16} range={spread:.4f}  rel={rel:.1%}")

    out = {
        "scope": {
            "topic": args.topic,
            "corpus_fingerprint": corpus_fp,
            "embedder_fingerprint": embedder_fp,
            "embedder": "GIST-small (avsolatorio/GIST-small-Embedding-v0, 384d)",
            "N_total": int(N_total),
            "tree_n": int(tree_n),
            "metric_n": int(n),
            "seed": args.seed,
            "work_types": list(_WT4),
        },
        "n_flat": args.n_flat,
        "sum_all_w_upper": sum_all_w,
        "random_dasgupta_baseline": rand_cost,
        "results": results,
        "winners": winners,
        "elapsed_s": round(time.time() - t0, 1),
        "provenance": _provenance(),
    }
    Path(args.out).write_text(json.dumps(out, indent=2))
    print(f"\n[done] {time.time()-t0:.1f}s  results -> {args.out}")


if __name__ == "__main__":
    main()

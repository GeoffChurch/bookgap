"""Part B (fallback) — 4-arm SPACE x TREE on hard books, IN-SPACE proxy metric.

The preferred Part-B path (compute each hard book's OWN close-loop gap, then run the real
``space_tree_recon_ab`` recon) is NOT FEASIBLE for the new CS-textbook candidates at field-17
scope: their nearest field-17 book is so close that the own-gap k-ball is EMPTY (boyd_convex,
sutton_barto_rl: gap_size=0; see ``artifacts/book_gaps/st_ab/partb_*_gap.json``). So this
script falls back to the in-space labeled-set PROXY the spec explicitly allows — the same recipe
``geometry_ceiling.py`` / ``toc_recovery.py`` use — and runs the 4-arm {denoiser, linkage} grid
on it, to test whether the average-linkage / PCA effect REPRODUCES on a second/third hard book.

Per hard book (the lowest-raw-separability books from ``hard_book_screen.py``):
  * labeled set = top-N=points_per_chap x n_chap field-17 articles by max-cosine to ANY gold
    chapter, argmax-cosine gold label (exactly ``geometry_ceiling._build_labeled_set``).
  * 4 arms = {NONE (raw GIST-small 384d), PCA-50} x {weighted_bisecting_kmeans, average-cosine}:
    cluster the SAME labeled points, flat-cut at k=n_chap (``fcluster`` for scipy trees;
    bisecting-kmeans uses its own leaf assignments cut), ARI/NMI vs the gold labels + a random
    baseline. PCA-50 is fit on the labeled set (unsupervised), applied to the points; the same
    points feed every arm so only {space, tree} vary.

This is the IN-SPACE analogue of the real-recon 4-arm A/B (``space_tree_recon_ab``), restricted
to the hardest screened books. It is OPTIMISTIC vs the real close-loop metric (the very thing the
color_image 0.887->0.007 case warns about), so it is reported as a PROXY: it shows whether the
levers' DIRECTION reproduces on more hard books, not their real-recon magnitude.

CAVEATS
-------
* PROXY metric: in-space flat-cut ARI on an argmax-cosine labeled set, NOT the close-loop recon.
  Absolute numbers are inflated (labels share the raw geometry); use the cross-arm deltas and the
  cross-book direction, and confirm magnitude only on the real metric where a gap exists.
* Field-17 scope, no per-book gap (own-gap empty); the labeled set is field articles nearest the
  book's chapters — a proxy for the book's own-gap article set.

Regenerate (do not edit the generated JSON by hand):

  .conda/bin/python -m artifacts_scripts.curriculum.dendro_eval.hard_book_4arm_proxy
"""
from __future__ import annotations

import argparse
import json
import shlex
import sys
import time
from pathlib import Path

import numpy as np
from numpy.typing import NDArray
from scipy.cluster.hierarchy import fcluster, linkage
from sklearn.decomposition import PCA
from sklearn.metrics import adjusted_rand_score, normalized_mutual_info_score

from artifacts_scripts.curriculum.dendro_eval.hard_book_screen import _build_labeled_set
from artifacts_scripts.curriculum.dendro_eval.toc_recovery import _load_article_space, _unit
from artifacts_scripts.curriculum.scalable_clustering import bisecting_kmeans_linkage
from bookgap.util import LOGGER, setup_logging

_MODULE = "artifacts_scripts.curriculum.dendro_eval.hard_book_4arm_proxy"
_HERE = Path(__file__).resolve().parent

# default hard books = the lowest-raw-separability from hard_book_screen.
_DEFAULT_HARD = ["boyd_convex", "sutton_barto_rl", "koller_pgm", "szeliski_cv"]
_PCA_DIM = 50
_SEED = 42


def _provenance() -> str:
    cmd = f"python -m {_MODULE} " + " ".join(shlex.quote(a) for a in sys.argv[1:])
    return f"Generated by `{cmd}`. Regenerate with the command above; do not edit by hand."


def _flat_labels(X: NDArray, linkage_method: str, k: int, seed: int) -> NDArray:
    """Cluster X into k flat clusters under the given tree. X is unit-norm f64."""
    n = X.shape[0]
    if linkage_method == "weighted_bisecting_kmeans":
        # repo default builder; cut its dendrogram at k via fcluster on the linkage.
        bk = bisecting_kmeans_linkage(
            X.astype(np.float32), min_cluster_size=1, max_depth=None,
            random_state=seed, use_minibatch=False, verbose=False,
        )
        Z = bk.linkage
        # bisecting-kmeans permutes leaves; map fcluster(leaf-order) back to point order.
        lca = bk.leaf_cluster_assignments  # point -> leaf_id (permutation when msc=1)
        flat_leaf = fcluster(Z, t=k, criterion="maxclust")  # indexed by leaf id
        return flat_leaf[lca]
    elif linkage_method == "average":
        Z = linkage(X.astype(np.float64), method="average", metric="cosine")
        return fcluster(Z, t=k, criterion="maxclust")
    raise ValueError(f"unknown linkage_method {linkage_method!r}")


def _space(X: NDArray, denoiser: str) -> NDArray:
    """Return the points in the requested space (unit-norm). PCA fit on X (unsupervised)."""
    if denoiser == "NONE":
        return _unit(X)
    if denoiser == "PCA":
        d = int(min(_PCA_DIM, X.shape[0], X.shape[1]))
        Z = PCA(n_components=d, random_state=0).fit_transform(X)
        return _unit(Z)
    raise ValueError(f"unknown denoiser {denoiser!r}")


_ARMS = {
    "NONE_bisecting": ("NONE", "weighted_bisecting_kmeans"),
    "NONE_average":   ("NONE", "average"),
    "PCA_bisecting":  ("PCA", "weighted_bisecting_kmeans"),
    "PCA_average":    ("PCA", "average"),
}


def _run_book(bk: dict, n_rand: int, seed: int) -> dict:
    X = bk.pop("X")
    labels = bk.pop("labels")
    n_chap = bk["n_chapters"]
    k = n_chap

    arms_out: dict = {}
    for arm, (den, link) in _ARMS.items():
        Xs = _space(X, den)
        flat = _flat_labels(Xs, link, k, seed)
        ari = float(adjusted_rand_score(labels, flat))
        nmi = float(normalized_mutual_info_score(labels, flat))
        # random baseline: shuffle gold, fixed flat clustering
        rng2 = np.random.default_rng(seed)
        rvals = [adjusted_rand_score(labels[rng2.permutation(len(labels))], flat)
                 for _ in range(n_rand)]
        ari_rand = float(np.mean(rvals)) if rvals else float("nan")
        arms_out[arm] = {
            "denoiser": den, "linkage": link, "dim": int(Xs.shape[1]),
            "ari": ari, "nmi": nmi, "ari_random": ari_rand,
            "ari_above_random": ari - ari_rand,
            "k_effective": int(len(np.unique(flat))),
        }
        LOGGER.info("[%s] %-16s dim=%-3d ARI=%.4f (rand %.4f, +%.4f) NMI=%.4f",
                    bk["slug"], arm, Xs.shape[1], ari, ari_rand, ari - ari_rand, nmi)

    def _ari_of(a: str) -> float:
        return float(arms_out[a]["ari"])
    deltas = {
        "pca_at_bisecting": _ari_of("PCA_bisecting") - _ari_of("NONE_bisecting"),
        "pca_at_average": _ari_of("PCA_average") - _ari_of("NONE_average"),
        "avg_at_none": _ari_of("NONE_average") - _ari_of("NONE_bisecting"),
        "avg_at_pca": _ari_of("PCA_average") - _ari_of("PCA_bisecting"),
        "joint": _ari_of("PCA_average") - _ari_of("NONE_bisecting"),
    }
    return {**bk, "arms": arms_out, "deltas": deltas}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--field", default="17")
    ap.add_argument("--books", nargs="*", default=None,
                    help="hard-book slugs (default: lowest-raw-sep from the screen).")
    ap.add_argument("--points-per-chap", type=int, default=60)
    ap.add_argument("--n-rand", type=int, default=20)
    ap.add_argument("--seed", type=int, default=_SEED)
    ap.add_argument("--out", default=str(_HERE / "hard_book_4arm_proxy_results.json"))
    args = ap.parse_args()

    setup_logging(log_name="hard_book_4arm_proxy", log_level="INFO", include_time=False,
                  log_path=Path(args.out).with_suffix(".log"))
    t0 = time.time()
    slugs = args.books if args.books else _DEFAULT_HARD

    LOGGER.info("Loading field-%s article space once...", args.field)
    art_ids, art_emb, _ = _load_article_space(None, args.field)
    LOGGER.info("Field-%s pool: %d works dim=%d", args.field, len(art_ids), art_emb.shape[1])

    books: list[dict] = []
    for slug in slugs:
        toc_name = f"{slug}_toc.json"
        bk = _build_labeled_set(toc_name, art_ids, art_emb, args.points_per_chap)
        if bk is None:
            LOGGER.warning("SKIP missing %s", toc_name)
            continue
        books.append(_run_book(bk, args.n_rand, args.seed))

    print("\n" + "=" * 96)
    print("PART-B HARD-BOOK 4-ARM PROXY — in-space flat-cut ARI (PROXY, not real recon)")
    print("=" * 96)
    for b in books:
        print(f"\n[{b['slug']}]  n_chap={b['n_chapters']}  N={b['n_labeled_points']}")
        hdr = f"    {'arm':<16}{'denoiser':<9}{'linkage':<26}{'ARI':>9}{'ARI>rand':>10}{'NMI':>8}"
        print(hdr)
        print("    " + "-" * (len(hdr) - 4))
        for arm, r in b["arms"].items():
            print(f"    {arm:<16}{r['denoiser']:<9}{r['linkage']:<26}"
                  f"{r['ari']:>9.4f}{r['ari_above_random']:>10.4f}{r['nmi']:>8.4f}")
        d = b["deltas"]
        print(f"    deltas: PCA@bis {d['pca_at_bisecting']:+.4f} PCA@avg {d['pca_at_average']:+.4f} | "
              f"avg@NONE {d['avg_at_none']:+.4f} avg@PCA {d['avg_at_pca']:+.4f} | "
              f"joint {d['joint']:+.4f}")

    out = {
        "field": args.field,
        "metric": "in_space_flat_cut_ARI_PROXY",
        "params": {"points_per_chap": args.points_per_chap, "n_rand": args.n_rand,
                   "seed": args.seed, "pca_dim": _PCA_DIM},
        "arm_definitions": {k: {"denoiser": v[0], "linkage": v[1]} for k, v in _ARMS.items()},
        "books": books,
        "caveats": {
            "proxy": ("in-space flat-cut ARI on an argmax-cosine labeled set, NOT the close-loop "
                      "recon; OPTIMISTIC (color_image was 0.887 in-space, 0.007 real). Shows lever "
                      "DIRECTION reproduction on more hard books, not real magnitude."),
            "why_not_real": ("the own-gap k-ball is EMPTY for these books at field-17 scope "
                             "(nearest field-17 book too close); the real recon needs a non-empty "
                             "gap-article set, so the proxy is the only feasible Part-B signal here."),
            "circularity": ("labels = argmax-cosine to same-space raw GIST-small chapter embeddings; "
                            "absolute ARI inflated, cross-arm deltas + cross-book direction usable."),
        },
        "elapsed_s": round(time.time() - t0, 1),
        "provenance": _provenance(),
    }
    Path(args.out).write_text(json.dumps(out, indent=2))
    print(f"\n[done] {time.time() - t0:.1f}s  results -> {args.out}")


if __name__ == "__main__":
    main()

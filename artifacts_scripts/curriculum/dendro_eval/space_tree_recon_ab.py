"""4-arm SPACE x TREE A/B on the REAL close-loop recon metric — the decisive test.

Prior stages (``toc_recovery.py`` flat-cut; ``geometry_ceiling.py`` supervised geometry
probe) suggested two curriculum levers on the HARD book cyberbullying:
  * a better TREE: scipy ``average``-linkage beat ``weighted_bisecting_kmeans`` at the
    flat-cut operating point (3/4 books), and
  * a better SPACE: an unsupervised ``PCA``-50 denoise lifted in-space separability
    (cyberbullying raw in-space ARI 0.121 -> PCA-50 0.368).
BUT those were OPTIMISTIC in-space probes: color_image scored 0.887 in-space yet its
REAL close-loop recon ARI is 0.007. So the levers are UNBANKED until they show on the
actual ``cl_<slug>_recon.json`` ``adjusted_rand_index``. This script runs that test.

Design — 4 arms per book, only {denoiser, linkage} vary
-------------------------------------------------------
For each book it drives the REAL pipeline (``book_curriculum`` -> ``book_toc_reconstruction``)
under 4 arms = {NONE, PCA} x {weighted_bisecting_kmeans, average}. The operating point is
held FIXED across all four: ``rank_before_clustering=True`` with the SAME ``ranking_top_k``
(default 5000) for every arm, so average-linkage (O(N^2)) is tractable and the ONLY things
that differ are the embedding space and the clustering tree.

* PCA arm: the repo's unsupervised ``PCA`` denoiser (``WorkDenoisers.PCA``), fit on the
  scope corpus, reducing GIST-small 384d -> ``384 - drop_k`` dims (default drop_k=334 =>
  PCA-50). It is applied CONSISTENTLY to the clustered works (via the cloud) AND to the
  gold chapters the recon embeds: ``book_toc_reconstruction`` projects the freshly-embedded
  chapters through the SAME ``cloud.denoiser_projection()`` so the chapter-assignment cosine
  and Track-A clustering live in one space.

* Sanity gate: the ``NONE x weighted_bisecting_kmeans`` arm is the internal baseline. The
  PUBLISHED A1 recon runs already used ``rank_before_clustering=True, ranking_top_k=5000,
  weighted_bisecting_kmeans, denoiser=NONE`` (see ``artifacts/curriculum/cl_A1_*/metadata.json``),
  i.e. EXACTLY this arm, so top-k is held the same as the published baseline and this arm
  should reproduce the published ARI (modulo bisecting-kmeans seed nondeterminism). The
  printed table puts the published ARI next to the internal baseline so the reader can
  confirm the gate before trusting the PCA/average deltas.

Metric: the recon ``adjusted_rand_index`` (+ ``normalized_mutual_info``, ``chapter_purity``),
per arm per book. Results factor the two levers (PCA-effect at fixed tree; linkage-effect at
fixed space; the joint corner) so they are separable.

Each (book, arm) runs in its own subprocess (the cloud cache + embedder GPU context are
per-process, and ``book_curriculum`` is "run ONE per process"), mirroring ``run_close_loop.sh``.
Results are written incrementally so a crash mid-sweep keeps completed arms.

Regenerate (do not edit the generated JSON by hand):

  .conda/bin/python -m artifacts_scripts.curriculum.dendro_eval.space_tree_recon_ab
"""
from __future__ import annotations

import argparse
import json
import os
import shlex
import subprocess
import sys
import time
from pathlib import Path
from typing import Optional

_MODULE = "artifacts_scripts.curriculum.dendro_eval.space_tree_recon_ab"
_HERE = Path(__file__).resolve().parent
_REPO = Path(__file__).resolve().parents[3]
_BOOK_GAPS = _REPO / "artifacts" / "book_gaps"
_CURR = _REPO / "artifacts" / "curriculum"
_PY = str(_REPO / ".conda" / "bin" / "python")

# (slug, book_id, n_chap, toc_json, gap_json, published_recon_json). Mirrors
# toc_recovery._BOOKS so the book set + scopes tie to the prior experiments.
_BOOKS = [
    ("cyberbullying", "W2898513995", 8,
     "W2898513995_toc.json", "W2898513995_cyberbullying_ai.json", "cl_cyberbullying_recon.json"),
    ("mcs", "W4235013513", 10,
     "W4235013513_toc.json", "mcs_gap.json", "cl_mcs_recon.json"),
    ("neuromorphic", "W4247813589", 13,
     "W4247813589_toc.json", "neuromorphic_gap.json", "cl_neuromorphic_recon.json"),
    ("color_image", "W4211017872", 24,
     "W4211017872_toc.json", "color_image_gap.json", "cl_color_image_recon.json"),
]

# arm key -> (denoiser, drop_k_or_None, linkage_method)
_ARMS = {
    "NONE_bisecting":  ("NONE", None, "weighted_bisecting_kmeans"),
    "NONE_average":    ("NONE", None, "average"),
    "PCA_bisecting":   ("PCA", 334, "weighted_bisecting_kmeans"),
    "PCA_average":     ("PCA", 334, "average"),
}


def _provenance() -> str:
    cmd = f"python -m {_MODULE} " + " ".join(shlex.quote(a) for a in sys.argv[1:])
    return f"Generated by `{cmd}`. Regenerate with the command above; do not edit by hand."


def _run(cmd: list[str], log: Path) -> int:
    """Run a subprocess, tee-ing combined stdout/stderr to *log*. Returns rc."""
    log.parent.mkdir(parents=True, exist_ok=True)
    env = dict(os.environ)
    env["CUDA_VISIBLE_DEVICES"] = ""          # never contend for the GPU (CPU recon)
    env["TOKENIZERS_PARALLELISM"] = "false"
    with log.open("w") as fh:
        proc = subprocess.run(cmd, cwd=str(_REPO), env=env, stdout=fh,
                              stderr=subprocess.STDOUT, text=True)
    return proc.returncode


def _run_arm(slug: str, gap: str, toc: str, n_chap: int, arm: str,
             top_k: int, logdir: Path) -> dict:
    """Build the curriculum and run the recon for one (book, arm). Returns a row dict."""
    denoiser, drop_k, linkage = _ARMS[arm]
    out_name = f"st_ab_{slug}_{arm}"
    curr_dir = _CURR / out_name
    recon_out = _BOOK_GAPS / "st_ab" / f"{slug}_{arm}_recon.json"
    gap_path = _BOOK_GAPS / gap
    toc_path = _BOOK_GAPS / toc

    row: dict = {"arm": arm, "denoiser": denoiser, "drop_k": drop_k,
                 "linkage": linkage, "ranking_top_k": top_k,
                 "curriculum_dir": str(curr_dir), "recon_json": str(recon_out)}

    # --- Track A: build OUR curriculum from the book's own gap under this arm.
    build_cmd = [
        _PY, "-m", "artifacts_scripts.curriculum.book_curriculum",
        "--gap-json", str(gap_path), "--desired-n-topics", str(n_chap),
        "--output-dir", out_name, "--no-plot",
        "--linkage-method", linkage,
    ]
    if denoiser != "NONE":
        build_cmd += ["--denoiser", denoiser]
        if drop_k is not None:
            build_cmd += ["--drop-k", str(drop_k)]
    # ranking_top_k is 5000 by default inside book_curriculum; override only if asked.
    if top_k != 5000:
        build_cmd += ["--ranking-top-k", str(top_k)]

    t0 = time.time()
    rc_build = _run(build_cmd, logdir / f"{slug}_{arm}_build.log")
    row["build_rc"] = rc_build
    row["build_s"] = round(time.time() - t0, 1)
    if rc_build != 0:
        row["status"] = "BUILD_FAILED"
        return row

    # --- Track B + recon: assign gap articles to gold chapters in the SAME space,
    # compare against OUR clusters. The denoiser/drop_k MUST match the build arm.
    recon_cmd = [
        _PY, "-m", "artifacts_scripts.curriculum.book_toc_reconstruction",
        "--gap-json", str(gap_path), "--toc-json", str(toc_path),
        "--curriculum-dir", str(curr_dir),
        "--out", str(recon_out),
    ]
    if denoiser != "NONE":
        recon_cmd += ["--denoiser", denoiser]
        if drop_k is not None:
            recon_cmd += ["--drop-k", str(drop_k)]

    t1 = time.time()
    rc_recon = _run(recon_cmd, logdir / f"{slug}_{arm}_recon.log")
    row["recon_rc"] = rc_recon
    row["recon_s"] = round(time.time() - t1, 1)
    if rc_recon != 0 or not recon_out.exists():
        row["status"] = "RECON_FAILED"
        return row

    rec = json.loads(recon_out.read_text())
    row.update({
        "status": "OK",
        "adjusted_rand_index": rec.get("adjusted_rand_index"),
        "normalized_mutual_info": rec.get("normalized_mutual_info"),
        "chapter_purity": rec.get("chapter_purity"),
        "n_gap_articles": rec.get("n_gap_articles"),
        "n_resolved": rec.get("n_resolved"),
        "n_shared_with_curriculum": rec.get("n_shared_with_curriculum"),
        "n_toc_chapters": rec.get("n_toc_chapters"),
        "n_our_clusters": rec.get("n_our_clusters"),
        "track_b_chapter_sizes": rec.get("track_b_chapter_sizes"),
    })
    return row


def _published_ari(recon_name: str) -> Optional[float]:
    p = _BOOK_GAPS / recon_name
    if not p.exists():
        return None
    try:
        return float(json.loads(p.read_text()).get("adjusted_rand_index"))
    except Exception:
        return None


def _save(out_path: Path, payload: dict) -> None:
    out_path.parent.mkdir(parents=True, exist_ok=True)
    tmp = out_path.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(payload, indent=2))
    os.replace(tmp, out_path)


def _print_book_table(book: dict) -> None:
    slug = book["slug"]
    pub = book.get("published_ari")
    pub_s = f"{pub:.4f}" if pub is not None else "  n/a"
    print(f"\n[{slug}]  scope({book['scope']})  n_chap={book['n_chap']}  "
          f"published_recon_ARI={pub_s}")
    hdr = (f"    {'arm':<16}{'denoiser':<9}{'linkage':<26}{'ARI':>9}{'NMI':>8}"
           f"{'purity':>8}{'shared':>8}{'clusters':>9}")
    print(hdr)
    print("    " + "-" * (len(hdr) - 4))
    for arm in _ARMS:
        r = book["arms"].get(arm, {})
        if r.get("status") != "OK":
            print(f"    {arm:<16}{r.get('denoiser',''):<9}{r.get('linkage',''):<26}"
                  f"{'  '+str(r.get('status','?')):>42}")
            continue
        ari = r.get("adjusted_rand_index"); nmi = r.get("normalized_mutual_info")
        pur = r.get("chapter_purity"); sh = r.get("n_shared_with_curriculum")
        nc = r.get("n_our_clusters")
        print(f"    {arm:<16}{r['denoiser']:<9}{r['linkage']:<26}"
              f"{ari:>9.4f}{nmi:>8.4f}{pur:>8.4f}{sh:>8}{nc:>9}")
    # factored deltas
    d = book.get("deltas", {})
    if d:
        print(f"    deltas:  PCA@bisecting {d.get('pca_at_bisecting'):+.4f}  "
              f"PCA@average {d.get('pca_at_average'):+.4f}   |   "
              f"avg@NONE {d.get('avg_at_none'):+.4f}  avg@PCA {d.get('avg_at_pca'):+.4f}   |   "
              f"joint(PCA_avg - NONE_bis) {d.get('joint'):+.4f}")


def _compute_deltas(arms: dict) -> dict:
    """Factor PCA-effect (fixed tree) and linkage-effect (fixed space)."""
    def ari(k: str) -> Optional[float]:
        r = arms.get(k, {})
        return r.get("adjusted_rand_index") if r.get("status") == "OK" else None

    nb, na = ari("NONE_bisecting"), ari("NONE_average")
    pb, pa = ari("PCA_bisecting"), ari("PCA_average")

    def sub(a: Optional[float], b: Optional[float]) -> Optional[float]:
        return (a - b) if (a is not None and b is not None) else None

    return {
        "pca_at_bisecting": sub(pb, nb),   # PCA effect, tree fixed = bisecting
        "pca_at_average": sub(pa, na),     # PCA effect, tree fixed = average
        "avg_at_none": sub(na, nb),        # average effect, space fixed = NONE
        "avg_at_pca": sub(pa, pb),         # average effect, space fixed = PCA
        "joint": sub(pa, nb),              # best corner vs baseline
    }


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--books", nargs="*", default=None,
                    help="subset of slugs to run (default: all 4).")
    ap.add_argument("--arms", nargs="*", default=None,
                    help=f"subset of arms to run (default: all). Options: {list(_ARMS)}")
    ap.add_argument("--ranking-top-k", type=int, default=5000,
                    help="top-k held fixed across ALL arms (default 5000, matching published A1).")
    ap.add_argument("--extra-books-manifest", default=None,
                    help="JSON file with a list of extra book tuples "
                         "[slug, book_id, n_chap, toc_json, gap_json, recon_json] to run IN ADDITION "
                         "to (or, with --books, filtered alongside) the default 4. Used by Part B to "
                         "feed hard-book candidates whose own-gap was just computed.")
    ap.add_argument("--out", default=str(_HERE / "space_tree_recon_ab_results.json"))
    args = ap.parse_args()

    all_books = list(_BOOKS)
    if args.extra_books_manifest:
        extra = json.loads(Path(args.extra_books_manifest).read_text())
        all_books += [tuple(t) for t in extra]
    books = [b for b in all_books if (args.books is None or b[0] in args.books)]
    arms = list(args.arms) if args.arms else list(_ARMS)
    for a in arms:
        if a not in _ARMS:
            raise SystemExit(f"unknown arm {a!r}; options: {list(_ARMS)}")

    out_path = Path(args.out)
    logdir = _HERE / "st_ab_logs"
    t0 = time.time()

    payload: dict = {
        "params": {"ranking_top_k": args.ranking_top_k, "arms": arms,
                   "pca_dim": 384 - 334, "drop_k": 334},
        "arm_definitions": {k: {"denoiser": v[0], "drop_k": v[1], "linkage": v[2]}
                            for k, v in _ARMS.items()},
        "books": [],
        "provenance": _provenance(),
    }

    for slug, book_id, n_chap, toc, gap, recon_name in books:
        print(f"\n{'='*78}\n=== {slug}  (book {book_id}, n_chap={n_chap}) ===\n{'='*78}")
        gap_json = json.loads((_BOOK_GAPS / gap).read_text())
        scope = {"subfield": gap_json.get("scope_subfield"),
                 "field": gap_json.get("scope_field")}
        book_row: dict = {
            "slug": slug, "book_id": book_id, "n_chap": n_chap, "scope": scope,
            "published_ari": _published_ari(recon_name),
            "arms": {},
        }
        for arm in arms:
            print(f"  --- {slug} / {arm}  {time.strftime('%H:%M:%S')} ---", flush=True)
            r = _run_arm(slug, gap, toc, n_chap, arm, args.ranking_top_k, logdir)
            book_row["arms"][arm] = r
            ari = r.get("adjusted_rand_index")
            print(f"      -> status={r['status']}  ARI={ari if ari is None else round(ari,4)}  "
                  f"build={r.get('build_s')}s recon={r.get('recon_s')}s", flush=True)
            # incremental save after EVERY arm so a crash keeps finished work.
            book_row["deltas"] = _compute_deltas(book_row["arms"])
            tmp_books = payload["books"] + [book_row]
            payload_now = dict(payload, books=tmp_books,
                               elapsed_s=round(time.time() - t0, 1))
            _save(out_path, payload_now)
        payload["books"].append(book_row)

    payload["elapsed_s"] = round(time.time() - t0, 1)
    _save(out_path, payload)

    # --- final tables
    print(f"\n\n{'#'*78}\n# 4-ARM SPACE x TREE RECON A/B — REAL close-loop adjusted_rand_index\n{'#'*78}")
    for b in payload["books"]:
        _print_book_table(b)
    print(f"\n[done] {time.time() - t0:.1f}s  results -> {out_path}")


if __name__ == "__main__":
    main()

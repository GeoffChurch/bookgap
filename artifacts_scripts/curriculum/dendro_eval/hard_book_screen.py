"""Part B — expand the hard-book set: cheap in-space raw-separability screen.

The space x tree lever's whole weakness is n=1 hard book (cyberbullying). This screen
finds MORE hard books — the cyberbullying analogues — by running the SAME cheap
in-space raw-separability probe (``geometry_ceiling``'s raw kNN-F1 / unsupervised ARI@k)
over the OTHER ToC books in ``artifacts/book_gaps/*_toc.json`` whose field is ingested,
then ranking by LOWEST raw separability.

These extra ToC books (Bishop PRML, CLRS, Goodfellow DL, ...) carry only book_id/title/
chapters — no gap JSON, so no per-book scope and no detected gap-article set. They are all
Computer-Science textbooks and field 17 (CS) IS ingested, so we screen them at FIELD 17
(the same scope mcs/neuromorphic/color_image used). The labeled point set is built EXACTLY
as ``geometry_ceiling``/``toc_recovery`` do — top-N articles by max-cosine to ANY gold
chapter, argmax-cosine gold label — but with N = points_per_chap x n_chapters (no recon
``n_gap_articles`` exists for these books) and scope passed directly.

Per book it reports, on a stratified held-out TEST split (fixed seed), for the RAW
GIST-small space and the cheap unsupervised PCA-50 space:
  * kNN chapter-classification macro-F1 + accuracy (is chapter info linearly present),
  * unsupervised ARI@n_chapters (average-linkage cosine flat cut) vs gold + a random
    baseline.
Books are ranked by raw separability (mean of normalized raw kNN-F1 and raw unsup-ARI-
above-random) so the LOWEST are the hard-book candidates for a Part-B 4-arm recon A/B.

CAVEATS (same circularity as the prior probes, plus a scope caveat)
-------------------------------------------------------------------
* Labels are argmax-cosine to the SAME-space (raw GIST-small) chapter embeddings, so
  ABSOLUTE numbers are inflated; the cross-BOOK ranking (who is hardest) and the raw->PCA
  delta are the usable signals.
* Field-17 screen: these CS textbooks have no per-book scope; field 17 is a coarse,
  generous corpus (6.8M works) for any single book, so the labeled set is the field's
  articles nearest the book's chapters — a proxy for the book's own-gap article set, not
  the detected gap. Flagged. A book that screens HARD here is a strong cyberbullying-
  analogue candidate; confirm on the real recon metric (space_tree_recon_ab) before banking.

Regenerate (do not edit the generated JSON by hand):

  .conda/bin/python -m artifacts_scripts.curriculum.dendro_eval.hard_book_screen
"""
from __future__ import annotations

import argparse
import json
import shlex
import sys
import time
from pathlib import Path

import numpy as np
from numpy.typing import NDArray
from sklearn.model_selection import train_test_split

from artifacts_scripts.curriculum.dendro_eval.geometry_ceiling import (
    _KNN_K,
    _PCA_DIM,
    _knn_readout,
    _space_pca,
    _space_raw,
    _unsup_ari_readout,
)
from artifacts_scripts.curriculum.dendro_eval.toc_recovery import (
    _embed_chapters,
    _load_article_space,
    _unit,
)
from bookgap.util import LOGGER, setup_logging

_MODULE = "artifacts_scripts.curriculum.dendro_eval.hard_book_screen"
_HERE = Path(__file__).resolve().parent
_BOOK_GAPS = Path("artifacts/book_gaps")

# CS textbook ToC files to screen at field 17 (the close-loop 4 are excluded — they have
# their own gap JSONs + recon; this is about NEW hard-book candidates).
_DEFAULT_TOCS = [
    "bishop_prml_toc.json", "goodfellow_dl_toc.json", "hastie_esl_toc.json",
    "murphy_ml_toc.json", "duda_hart_pc_toc.json", "russell_norvig_aima_toc.json",
    "jurafsky_toc.json", "koehn_toc.json", "manning_ir_toc.json",
    "manning_schutze_fsnlp_toc.json", "sutton_barto_rl_toc.json", "szeliski_cv_toc.json",
    "tan_dm_toc.json", "koller_pgm_toc.json", "deisenroth_mml_toc.json",
    "james_islr_toc.json", "shalev_shwartz_uml_toc.json", "clrs_toc.json",
    "boyd_convex_toc.json", "cover_thomas_it_toc.json", "mackay_itila_toc.json",
    "gelman_bda_toc.json",
]

_MIN_PER_CHAP = 5


def _provenance() -> str:
    cmd = f"python -m {_MODULE} " + " ".join(shlex.quote(a) for a in sys.argv[1:])
    return f"Generated by `{cmd}`. Regenerate with the command above; do not edit by hand."


def _build_labeled_set(toc_name: str, art_ids: list[str], art_emb: NDArray,
                       points_per_chap: int) -> dict | None:
    """top-N by max-cosine to ANY chapter; argmax-cosine gold label (geometry_ceiling recipe).

    art_ids/art_emb are the (cached) field-17 article space, loaded once and shared across
    books. N = points_per_chap x n_chapters (no recon n_gap_articles for these books).
    """
    toc_path = _BOOK_GAPS / toc_name
    if not toc_path.exists():
        return None
    toc = json.loads(toc_path.read_text())
    chapters = toc["chapters"]
    n_chap = len(chapters)

    chap_emb = _unit(_embed_chapters(chapters))             # (n_chap, d) f64
    chap_f32 = chap_emb.astype(np.float32)
    art_norm = art_emb / np.maximum(
        np.linalg.norm(art_emb, axis=1, keepdims=True), np.float32(1e-12))
    sims_all = art_norm @ chap_f32.T                        # (N_pool, n_chap) f32
    max_sim = sims_all.max(axis=1)
    N = min(points_per_chap * n_chap, len(art_ids))
    top_idx = np.argpartition(-max_sim, N - 1)[:N] if N < len(max_sim) else np.arange(len(max_sim))
    top_idx = np.sort(top_idx)
    X = _unit(art_emb[top_idx])
    labels = sims_all[top_idx].argmax(axis=1).astype(int)
    label_sizes = np.bincount(labels, minlength=n_chap)
    return {
        "slug": toc_name.replace("_toc.json", ""),
        "title": toc.get("title", ""),
        "n_chapters": n_chap,
        "n_labeled_points": int(X.shape[0]),
        "top_n": int(N),
        "chapter_label_sizes": label_sizes.astype(int).tolist(),
        "X": X,
        "labels": labels,
    }


def _screen_book(bk: dict, test_frac: float, n_rand: int, seed: int) -> dict:
    """raw + PCA-50 readouts on a stratified TEST split for one book."""
    slug = bk["slug"]
    X = bk.pop("X")
    labels = bk.pop("labels")
    n_chap = bk["n_chapters"]
    label_sizes = np.asarray(bk["chapter_label_sizes"])

    present = np.flatnonzero(label_sizes > 0)
    singletons = [int(c) for c in present if label_sizes[c] < 2]
    if singletons:
        keep = ~np.isin(labels, singletons)
        X = X[keep]
        labels = labels[keep]
    idx = np.arange(X.shape[0])
    tr_idx, te_idx = train_test_split(idx, test_size=test_frac, random_state=seed,
                                      stratify=labels)
    Xtr, Xte = X[tr_idx], X[te_idx]
    ytr, yte = labels[tr_idx], labels[te_idx]
    k = n_chap
    unstable = [int(c) for c in np.unique(labels) if label_sizes[c] < _MIN_PER_CHAP]

    rows = []
    for sname, fitter in (("raw", _space_raw), ("pca50", _space_pca)):
        Ztr, Zte, sinfo = fitter(Xtr, Xte, ytr)
        knn = _knn_readout(Ztr, ytr, Zte, yte, _KNN_K)
        rng = np.random.default_rng(seed)
        ari = _unsup_ari_readout(Zte, yte, k, n_rand, rng)
        rows.append({"space": sname, **sinfo, **knn, **ari})

    by = {r["space"]: r for r in rows}
    raw_f1 = by["raw"]["knn_macro_f1"]
    raw_ari_rel = by["raw"]["unsup_ari_above_random"]
    # hardness score: lower = harder. mean of raw kNN-F1 and clamped raw ARI-above-random.
    raw_sep = float(np.mean([raw_f1, max(0.0, raw_ari_rel)]))
    LOGGER.info("[%s] n_chap=%d N=%d n_train=%d n_test=%d | raw F1=%.3f ARI>rand=%.3f "
                "-> raw_sep=%.3f | pca F1=%.3f ARI>rand=%.3f", slug, n_chap,
                bk["n_labeled_points"], len(tr_idx), len(te_idx), raw_f1, raw_ari_rel,
                raw_sep, by["pca50"]["knn_macro_f1"], by["pca50"]["unsup_ari_above_random"])
    return {
        **bk,
        "n_train": int(len(tr_idx)),
        "n_test": int(len(te_idx)),
        "unstable_classes_lt5": unstable,
        "spaces": rows,
        "raw_separability": raw_sep,
        "raw_knn_f1": raw_f1,
        "raw_unsup_ari_above_random": float(raw_ari_rel),
        "pca_knn_f1": float(by["pca50"]["knn_macro_f1"]),
        "pca_unsup_ari_above_random": float(by["pca50"]["unsup_ari_above_random"]),
        "pca_minus_raw_knn_f1": float(by["pca50"]["knn_macro_f1"] - raw_f1),
        "pca_minus_raw_unsup_ari": float(by["pca50"]["unsup_ari"] - by["raw"]["unsup_ari"]),
    }


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--field", default="17", help="ingested field to screen at (default 17 = CS).")
    ap.add_argument("--tocs", nargs="*", default=None,
                    help="ToC filenames to screen (default: the CS textbook set).")
    ap.add_argument("--points-per-chap", type=int, default=60,
                    help="labeled points per chapter (top-N = this x n_chapters).")
    ap.add_argument("--test-frac", type=float, default=0.30)
    ap.add_argument("--n-rand", type=int, default=20)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--out", default=str(_HERE / "hard_book_screen_results.json"))
    args = ap.parse_args()

    setup_logging(log_name="hard_book_screen", log_level="INFO", include_time=False,
                  log_path=Path(args.out).with_suffix(".log"))
    t0 = time.time()
    tocs = args.tocs if args.tocs else _DEFAULT_TOCS

    LOGGER.info("Loading field-%s article space once (shared across %d books)...",
                args.field, len(tocs))
    art_ids, art_emb, _ = _load_article_space(None, args.field)
    LOGGER.info("Field-%s article pool: %d works, dim=%d", args.field, len(art_ids),
                art_emb.shape[1])

    books: list[dict] = []
    for toc_name in tocs:
        try:
            bk = _build_labeled_set(toc_name, art_ids, art_emb, args.points_per_chap)
            if bk is None:
                LOGGER.warning("SKIP missing %s", toc_name)
                continue
            res = _screen_book(bk, args.test_frac, args.n_rand, args.seed)
        except Exception as exc:  # noqa: BLE001 — skip-and-proceed
            LOGGER.exception("[%s] failed; skipping", toc_name)
            books.append({"slug": toc_name.replace("_toc.json", ""), "skipped": str(exc)})
            continue
        books.append(res)

    live = [b for b in books if not b.get("skipped")]
    live.sort(key=lambda b: b["raw_separability"])  # hardest first

    print("\n" + "=" * 104)
    print(f"HARD-BOOK SCREEN — raw separability at field {args.field} (HARDEST first; "
          f"these are the cyberbullying analogues)")
    print("=" * 104)
    hdr = (f"  {'book':<24}{'n_chap':>7}{'N':>7}{'raw_F1':>9}{'raw_ARI>r':>11}"
           f"{'raw_sep':>9}{'pca_F1':>9}{'pca_ARI>r':>11}{'dF1':>8}{'dARI':>8}")
    print(hdr)
    print("  " + "-" * (len(hdr) - 2))
    for b in live:
        print(f"  {b['slug']:<24}{b['n_chapters']:>7}{b['n_labeled_points']:>7}"
              f"{b['raw_knn_f1']:>9.3f}{b['raw_unsup_ari_above_random']:>11.3f}"
              f"{b['raw_separability']:>9.3f}{b['pca_knn_f1']:>9.3f}"
              f"{b['pca_unsup_ari_above_random']:>11.3f}"
              f"{b['pca_minus_raw_knn_f1']:>+8.3f}{b['pca_minus_raw_unsup_ari']:>+8.3f}")

    hardest = [b["slug"] for b in live[:3]]
    print(f"\n  HARDEST 3 (lowest raw separability) -> Part-B recon A/B candidates: {hardest}")
    print("  (NOTE: field-17 screen, no per-book gap; labeled set is a proxy for the book's "
          "own-gap\n   article set. Confirm on the real recon metric before banking.)")

    out = {
        "field": args.field,
        "params": {"points_per_chap": args.points_per_chap, "test_frac": args.test_frac,
                   "n_rand": args.n_rand, "seed": args.seed, "knn_k": _KNN_K,
                   "pca_dim": _PCA_DIM},
        "books_ranked_hardest_first": live,
        "skipped": [b for b in books if b.get("skipped")],
        "hardest_candidates": hardest,
        "caveats": {
            "scope": (f"CS textbooks screened at FIELD {args.field} (no per-book scope; "
                      "field is a coarse proxy corpus for any single book)."),
            "circularity": ("labels = argmax-cosine to same-space raw GIST-small chapter "
                            "embeddings; absolute numbers inflated, cross-book ranking + "
                            "raw->PCA delta are the usable signals."),
            "proxy": ("labeled set = field articles nearest the book's chapters, a proxy for "
                      "the book's own detected gap-article set; a hard screen flags a candidate, "
                      "the real recon metric (space_tree_recon_ab) confirms it."),
        },
        "elapsed_s": round(time.time() - t0, 1),
        "provenance": _provenance(),
    }
    Path(args.out).write_text(json.dumps(out, indent=2))
    print(f"\n[done] {time.time() - t0:.1f}s  results -> {args.out}")


if __name__ == "__main__":
    main()

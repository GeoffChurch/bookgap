"""Summarize multiple eval_pairwise_judge result JSONs into one cross-book table.

Writes a markdown summary (book x dimension winners + an ours win/tie/lose tally)
to --out. Reusable across any set of pairwise eval results.

Example:
  python -m artifacts_scripts.curriculum.export_eval_summary \\
      --eval-json artifacts/curriculum_eval_pairwise/mcs_sem_dk_pairwise.json \\
                  artifacts/curriculum_eval_pairwise/neuromorphic_sem_dk_pairwise.json \\
                  artifacts/curriculum_eval_pairwise/color_image_sem_dk_pairwise.json \\
      --out docs/curriculum_eval_examples/results_summary.md
"""
import argparse
import json
import shlex
import sys
from pathlib import Path

_MODULE = "artifacts_scripts.curriculum.export_eval_summary"


def _provenance() -> str:
    cmd = f"python -m {_MODULE} " + " ".join(shlex.quote(a) for a in sys.argv[1:])
    return ("\n\n---\n"
            f"*Generated by `{cmd}`*  \n"
            "*Regenerate with the command above; do not edit by hand.*\n")


def _norm(winner: str, label_a: str, label_b: str) -> str:
    if winner == label_a:
        return "ours"
    if winner == label_b:
        return "book"
    return "tie"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--eval-json", nargs="+", required=True, help="pairwise result JSONs")
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--title", default="Curriculum ToC-reconstruction eval — all books")
    args = ap.parse_args()

    rows = [json.loads(Path(p).read_text()) for p in args.eval_json]
    dims = list(rows[0]["dims"].keys())
    models = sorted({r["model"] for r in rows})

    out = [
        f"# {args.title}", "",
        f"Pairwise judge: {', '.join(models)} ({rows[0]['repeats']} repeats/order, de-randomized). "
        "**ours** = our gap-seeded curriculum (semantic re-rank + dynamic-k); **book** = the book's "
        "real ToC. A cell is a config only when it is preferred in BOTH presentation orders; an "
        "order-flip or genuine tie → `tie`.", "",
        "| Book | " + " | ".join(dims) + " |",
        "| :--- |" + " :---: |" * len(dims),
    ]
    for r in rows:
        cells = [_norm(r["dims"][d]["winner"], r["label_a"], r["label_b"]) for d in dims]
        out.append(f"| {r['topic']} | " + " | ".join(cells) + " |")

    out += [
        "", f"**ours win / tie / book win (of {len(rows)} books):**", "",
        "| Dimension | ours wins | ties | book wins |",
        "| :--- | :---: | :---: | :---: |",
    ]
    for d in dims:
        vals = [_norm(r["dims"][d]["winner"], r["label_a"], r["label_b"]) for r in rows]
        out.append(f"| {d} | {vals.count('ours')} | {vals.count('tie')} | {vals.count('book')} |")

    out += [
        "", "Per-book detail (un-aggregated per-order verdicts + judge comments) is in each book's "
        "`<book>/eval_results.md`; the three curricula being compared are the sibling "
        "`ours_curriculum.md` / `toc_derived_curriculum.md` / `original_book.md`.",
    ]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(out) + _provenance())
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()

"""Export the three sides of one ToC-reconstruction case as readable markdown:

  1. ours_curriculum.md         -- our generated curriculum (Track A, from the book's gap)
  2. original_book.md           -- the real book: title + abstract + table of contents
  3. toc_derived_curriculum.md  -- the curriculum derived from the book's real ToC (Track B)

Reusable across books. Tracks A/B are read straight from their curriculum run-dirs
(via eval_book_judge.load_book_outline -- same parse the LLM judge uses), so the
markdown matches exactly what was evaluated. The book's abstract is fetched from the
OpenAlex API (falls back to the ToC json's description for external books).

Example:
  uv run python -m artifacts_scripts.curriculum.export_curriculum_markdown \
      --track-a artifacts/curriculum/mcs_trackA \
      --track-b artifacts/curriculum/mcs_trackB \
      --toc-json artifacts/book_gaps/W4235013513_toc.json \
      --out-dir docs/curriculum_eval_examples/mobile_crowdsensing
"""
import argparse
import json
import shlex
import sys
import urllib.request
from pathlib import Path

from artifacts_scripts.curriculum.eval_book_judge import load_book_outline

_MODULE = "artifacts_scripts.curriculum.export_curriculum_markdown"


def _provenance() -> str:
    """Footer pointing back to the exact command that generated the file.

    All generated/derived files should carry this so a reader can rediscover and
    re-run the producing script with the same arguments (see project convention
    in CLAUDE.md)."""
    cmd = f"python -m {_MODULE} " + " ".join(shlex.quote(a) for a in sys.argv[1:])
    return ("\n\n---\n"
            f"*Generated by `{cmd}`*  \n"
            "*Regenerate with the command above; do not edit by hand.*\n")


def _render_curriculum_md(run_dir: str, heading: str, n_keywords: int = 30, n_works: int = 5) -> str:
    bo = load_book_outline(Path(run_dir))
    out = [f"# {bo.topic} — {heading}", "",
           f"*{len(bo.chapters)} chapters, in learning order.*", ""]
    for ch in bo.chapters:
        out += [f"## Chapter {ch.idx}: {ch.label}", ""]
        # Backtick each keyword: keeps underscores in phrase-mined terms
        # (neural_networks) literal (no markdown italic interpretation), grep-able,
        # and visually delimits each phrase as a single unit.
        kw = ", ".join(f"`{k}`" for k in ch.keywords[:n_keywords]) or "(none)"
        out += [f"**Key topics:** {kw}", ""]
        if ch.titles:
            out.append("**Representative works:**")
            out += [f"- {t}" for t in ch.titles[:n_works]]
            out.append("")
    return "\n".join(out)


def _fetch_abstract(book_id) -> str | None:
    if not book_id or not str(book_id).startswith("https://openalex.org/W"):
        return None
    try:
        wid = str(book_id).rsplit("/", 1)[-1]
        url = (f"https://api.openalex.org/works/{wid}"
               "?select=abstract_inverted_index&mailto=geoffrey.a.churchill@gmail.com")
        with urllib.request.urlopen(url, timeout=25) as r:
            inv = json.load(r).get("abstract_inverted_index")
        if not inv:
            return None
        pos = {i: w for w, idxs in inv.items() for i in idxs}
        return " ".join(pos[i] for i in sorted(pos))
    except Exception:
        return None


def _render_book_md(toc_json: str) -> str:
    toc = json.loads(Path(toc_json).read_text())
    title, wid = toc["title"], toc.get("book_id")
    abstract = _fetch_abstract(wid) or toc.get("query_text") or "*(abstract unavailable)*"
    out = [f"# {title} — original book", "",
           f"**OpenAlex id:** {wid}", "",
           "## Abstract", "", abstract, "",
           "## Table of Contents (the real book)", ""]
    for c in toc["chapters"]:
        line = f"{c['n']}. **{c['title']}**"
        desc = c.get("description")
        if desc:
            line += f" — {desc}"
        out.append(line)
    return "\n".join(out) + "\n"


def _order_to_config(verdict: str, order: int, label_a: str, label_b: str) -> str:
    """Map a presentation-space verdict (A/B/tie) back to a config label.

    Order 1 presents A=label_a (ours), B=label_b (book). Order 2 swaps them, so
    A=label_b (book), B=label_a (ours). Reproduces the judge's de-randomization."""
    if verdict == "tie":
        return "tie"
    if order == 1:
        return label_a if verdict == "A" else label_b
    return label_b if verdict == "A" else label_a


def _render_eval_md(eval_json: str) -> str:
    """Render an eval_pairwise_judge result JSON as readable markdown."""
    r = json.loads(Path(eval_json).read_text())
    a, b = r["label_a"], r["label_b"]
    out = [
        f"# {r['topic']} — pairwise eval (ours vs book ToC)", "",
        f"**Judge:** {r['model']} &nbsp;|&nbsp; **repeats:** {r['repeats']}/order "
        f"&nbsp;|&nbsp; **A:** {a} (ours) &nbsp;|&nbsp; **B:** {b} (book ToC)", "",
        f"**Parse/transport failures:** {r['n_parse_failures']}/{r['n_ollama_calls']} "
        f"({r['parse_failure_rate']:.0%})", "",
        "Un-aggregated per-repeat verdicts, mapped back to the config preferred (ours/book/tie) "
        "in each presentation order, alongside the de-randomized winner:", "",
        "| Dimension | ours shown first (per repeat) | book shown first (per repeat) | Winner |",
        "| :--- | :--- | :--- | :--- |",
    ]
    for dim, v in r["dims"].items():
        r1 = v.get("order1_repeat_verdicts", [v["order1_verdict"]])
        r2 = v.get("order2_repeat_verdicts", [v["order2_verdict"]])
        c1 = " · ".join(_order_to_config(x, 1, a, b) for x in r1) or "—"
        c2 = " · ".join(_order_to_config(x, 2, a, b) for x in r2) or "—"
        out.append(f"| {dim} | {c1} | {c2} | {v['winner']} |")
    out += [
        "", "*Each cell lists the individual per-repeat verdicts in that presentation order "
        "(mapped from presentation A/B back to ours/book). A per-order verdict is the strict "
        "majority of its repeats; the **Winner** is a config name only when the same config is "
        "preferred in BOTH orders, else \"tie\" (position-bias guard).*", "",
        "## Judge comments", "",
    ]
    for dim, v in r["dims"].items():
        out += [f"### {dim} — {v['winner']}", ""]
        seen: list = []
        for c in v.get("comments", []):
            if c not in seen:
                seen.append(c)
        out += [f"- {c}" for c in seen] + [""]
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--track-a", required=True, help="our curriculum run-dir (Track A)")
    ap.add_argument("--track-b", help="ToC-derived curriculum run-dir (Track B); not needed with --only-ours")
    ap.add_argument("--toc-json", help="the book's ToC json (title + chapters + book_id); not needed with --only-ours")
    ap.add_argument("--out-dir", required=True, type=Path)
    ap.add_argument("--eval-json", default=None,
                    help="optional eval_pairwise_judge result JSON; if given, also write eval_results.md")
    ap.add_argument("--only-ours", action="store_true",
                    help="regenerate only ours_curriculum.md (Track A); leave the book + Track B "
                         "files untouched. Use after improving the Track A curriculum.")
    args = ap.parse_args()
    if not args.only_ours and (not args.track_b or not args.toc_json):
        ap.error("--track-b and --toc-json are required unless --only-ours is set")
    args.out_dir.mkdir(parents=True, exist_ok=True)
    prov = _provenance()
    written = ["ours_curriculum.md"]
    (args.out_dir / "ours_curriculum.md").write_text(
        _render_curriculum_md(args.track_a, "our generated curriculum (from the book's gap)") + prov)
    if args.eval_json:
        (args.out_dir / "eval_results.md").write_text(_render_eval_md(args.eval_json) + prov)
        written.append("eval_results.md")
    if args.only_ours:
        print(f"wrote {', '.join(written)} -> {args.out_dir}")
        return
    (args.out_dir / "toc_derived_curriculum.md").write_text(
        _render_curriculum_md(args.track_b, "curriculum derived from the book's real ToC") + prov)
    (args.out_dir / "original_book.md").write_text(_render_book_md(args.toc_json) + prov)
    written += ["original_book.md", "toc_derived_curriculum.md"]
    print(f"wrote {', '.join(written)} -> {args.out_dir}")


if __name__ == "__main__":
    main()

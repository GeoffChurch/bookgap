"""Chapter-to-chapter correspondence between two curricula (matrix-first eval).

The raw, knob-free object is the chapter x chapter probe MATRIX between curriculum
A and curriculum B (each chapter = a weighted set of works). UOT/Hungarian is an
optional reduction (alignment + scalar + comprehensiveness gap) on top.

Probes (taxonomy axes: kernel = identity->geometry, direction = symmetric->directed):
  - ruzicka       : work-identity, symmetric (weighted Jaccard; here uniform = Jaccard)
  - containment_A : work-identity, directed  (|A_i ∩ B_j| / |A_i|: is our chapter ⊆ a book chapter)
  - centroid_cos  : embedding-centroid, symmetric (cosine of membership-weighted means)
  - cover_A       : embedding-distribution, directed (mean over A_i works of max cos to a B_j work)

Reductions:
  - Hungarian 1-1 alignment on a chosen probe (greedy/coherent correspondence).
  - Unbalanced Sinkhorn UOT: transported mass + per-side unmatched mass
    (= comprehensiveness gap: book chapters with no good match).

Also computes the A-vs-A matrix off-diagonal (internal redundancy — the FL/DPP diagnostic).
Non-invasive; reads both run-dirs' topic_work_ids.json + the cloud embeddings.

Example:
  python -m artifacts_scripts.curriculum.gap_chapter_correspondence \\
      --run-a artifacts/curriculum/neuromorphic_trackA_sem \\
      --run-b artifacts/curriculum/neuromorphic_trackB --field 17 \\
      --out docs/curriculum_eval_examples/neuromorphic_photonics/chapter_correspondence.md
"""
from __future__ import annotations

import argparse
import json
import shlex
import sys
from pathlib import Path

import numpy as np
from hydra.utils import instantiate
from omegaconf import OmegaConf
from scipy.optimize import linear_sum_assignment

from artifacts_scripts.curriculum.config import CurriculumConfig
from artifacts_scripts.curriculum.gap_fuzzy_topics import _unit
from bookgap.util import LOGGER, setup_logging

_MODULE = "artifacts_scripts.curriculum.gap_chapter_correspondence"


def _provenance() -> str:
    cmd = f"python -m {_MODULE} " + " ".join(shlex.quote(a) for a in sys.argv[1:])
    return f"\n\n---\n*Generated by `{cmd}`*  \n*Regenerate with the command above; do not edit by hand.*\n"


def _chapters(run_dir: Path) -> list:
    twi = json.loads((run_dir / "topic_work_ids.json").read_text())
    return [twi[k] for k in sorted(twi, key=lambda x: int(x))]


def _matrices(A: list, B: list, emb_of: dict):
    """Return probe matrices (nA x nB): ruzicka, containment_A, centroid_cos, cover_A."""
    As = [set(c) for c in A]
    Bs = [set(c) for c in B]
    Ac = [_unit(np.mean([emb_of[w] for w in c if w in emb_of] or [np.zeros(384)], 0)[None])[0] for c in A]
    Bc = [_unit(np.mean([emb_of[w] for w in c if w in emb_of] or [np.zeros(384)], 0)[None])[0] for c in B]
    Ae = [_unit(np.array([emb_of[w] for w in c if w in emb_of] or [np.zeros(384)])) for c in A]
    Be = [_unit(np.array([emb_of[w] for w in c if w in emb_of] or [np.zeros(384)])) for c in B]
    nA, nB = len(A), len(B)
    ruz = np.zeros((nA, nB)); con = np.zeros((nA, nB)); cen = np.zeros((nA, nB)); cov = np.zeros((nA, nB))
    for i in range(nA):
        for j in range(nB):
            inter = len(As[i] & Bs[j]); union = len(As[i] | Bs[j])
            ruz[i, j] = inter / union if union else 0.0
            con[i, j] = inter / len(As[i]) if As[i] else 0.0
            cen[i, j] = float(Ac[i] @ Bc[j])
            cov[i, j] = float((Ae[i] @ Be[j].T).max(1).mean()) if len(Ae[i]) and len(Be[j]) else 0.0
    return {"ruzicka": ruz, "containment_A": con, "centroid_cos": cen, "cover_A": cov}


def _uot_sinkhorn(C, a, b, eps=0.05, rho=0.5, iters=300):
    """Unbalanced (KL-penalized) Sinkhorn. Returns transport plan P (mass may be dropped)."""
    K = np.exp(-C / eps)
    u = np.ones(len(a)); v = np.ones(len(b))
    f = rho / (rho + eps)
    for _ in range(iters):
        u = (a / np.maximum(K @ v, 1e-30)) ** f
        v = (b / np.maximum(K.T @ u, 1e-30)) ** f
    return u[:, None] * K * v[None, :]


def _fmt(M, rlab, clab):
    out = ["| | " + " | ".join(clab) + " |", "| :-- |" + " :--: |" * len(clab)]
    for i, r in enumerate(rlab):
        out.append(f"| {r} | " + " | ".join(f"{M[i, j]:.2f}" for j in range(M.shape[1])) + " |")
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--run-a", required=True, type=Path)
    ap.add_argument("--run-b", required=True, type=Path)
    ap.add_argument("--field", default="17")
    ap.add_argument("--align-probe", default="centroid_cos")
    ap.add_argument("--out", default=None, type=Path)
    args = ap.parse_args()
    setup_logging(log_name="chapter_corr", log_level="INFO", include_time=False)

    A, B = _chapters(args.run_a), _chapters(args.run_b)
    cfg = OmegaConf.structured(CurriculumConfig())
    cfg.experiment.cloud.filter_pair.pre.field = str(args.field)
    cloud = instantiate(cfg.experiment.cloud)
    wid = cloud.work_ids(); E = np.asarray(cloud.embeddings(), dtype=np.float32)
    need = {w for c in A + B for w in c}
    emb_of = {w: E[i] for i, w in enumerate(wid) if w in need}

    mats = _matrices(A, B, emb_of)
    nA, nB = len(A), len(B)
    rlab = [f"A{i}" for i in range(nA)]; clab = [f"B{j}" for j in range(nB)]

    # Hungarian 1-1 alignment on the chosen probe (pad to square via cost = 1 - sim).
    S = mats[args.align_probe]
    n = max(nA, nB)
    cost = np.ones((n, n))
    cost[:nA, :nB] = 1.0 - S
    ri, ci = linear_sum_assignment(cost)
    pairs = [(int(r), int(c)) for r, c in zip(ri, ci) if r < nA and c < nB]

    # UOT (unbalanced) on the same cost -> transported / unmatched mass (comprehensiveness gap).
    a = np.ones(nA) / nA; b = np.ones(nB) / nB
    P = _uot_sinkhorn(1.0 - S, a, b)
    transported = float(P.sum())
    b_unmatched = float(np.clip(b - P.sum(0), 0, None).sum())   # book mass with no match
    a_unmatched = float(np.clip(a - P.sum(1), 0, None).sum())

    # Internal redundancy (A-vs-A centroid cosine off-diagonal) — the FL/DPP diagnostic.
    Ac = np.stack([_unit(np.mean([emb_of[w] for w in c if w in emb_of] or [np.zeros(384)], 0)[None])[0] for c in A])
    G = Ac @ Ac.T; np.fill_diagonal(G, -1)
    iu = np.triu_indices(nA, 1); redundancy = float(G[iu].max()) if nA > 1 else 0.0

    lines = [f"# Chapter correspondence — {args.run_a.name} (A) vs {args.run_b.name} (B)", "",
             f"A: {nA} chapters · B: {nB} chapters · align-probe: `{args.align_probe}`", "",
             f"**Hungarian 1-1 alignment** (probe `{args.align_probe}`):", ""]
    for r, c in pairs:
        lines.append(f"- A{r} ↔ B{c}  ({args.align_probe}={S[r, c]:.2f}, ruzicka={mats['ruzicka'][r, c]:.2f}, "
                     f"containment_A={mats['containment_A'][r, c]:.2f})")
    lines += ["",
              f"**UOT** (unbalanced): transported mass {transported:.2f} of 1.0; "
              f"book-side unmatched (comprehensiveness gap) **{b_unmatched:.2f}**, ours-side unmatched {a_unmatched:.2f}.",
              f"**Internal redundancy** of A (max off-diagonal centroid cosine): {redundancy:.2f}.", ""]
    for name in ("centroid_cos", "ruzicka", "containment_A", "cover_A"):
        lines += [f"## {name}", "", _fmt(mats[name], rlab, clab), ""]

    report = "\n".join(lines)
    print(report)
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(report + _provenance())
        print(f"\nwrote {args.out}")


if __name__ == "__main__":
    main()

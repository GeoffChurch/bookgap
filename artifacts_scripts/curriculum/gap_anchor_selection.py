"""Topic-anchor selection — FL / DPP prototype (non-invasive).

The dendrogram cut can produce REDUNDANT topics (e.g. Color Image's ~8
near-duplicate histogram-equalization chapters). Facility-location (max coverage)
and DPP (determinantal, diversity) select N anchors that are mutually dissimilar,
attacking that defect — the one thing product-of-experts / dynamic-k / soft
membership don't touch (see docs/backlog/curriculum-fuzzy-soft-topic-membership.md
and curriculum-specificity-semantic-reweight.md).

This prototype loads a built run-dir + cloud and compares three N-anchor sets on
**redundancy** (pairwise cosine among anchors; lower = more diverse) and
**coverage** (mass-weighted mean nearest-anchor similarity; higher = better):
  - dendrogram : the current topic centroids (mass-weighted means of hard members)
  - facility   : greedy max-coverage over the top-mass works (the fl_bookdemand
                 family's objective, validated for gap deflation)
  - dpp        : greedy MAP-DPP (quality = log1p(mass), similarity = cosine)

It does NOT modify the pipeline; it reports whether FL/DPP would de-duplicate the
anchor set before any integration.

Example:
  python -m artifacts_scripts.curriculum.gap_anchor_selection \\
      --run-dir artifacts/curriculum/color_image_trackA_sem --field 17 \\
      --out docs/curriculum_eval_examples/color_image_processing/anchor_selection_probe.md
"""
from __future__ import annotations

import argparse
import json
import math
import shlex
import sys
from pathlib import Path

import numpy as np
from hydra.utils import instantiate
from omegaconf import OmegaConf

from artifacts_scripts.curriculum.config import CurriculumConfig
from artifacts_scripts.curriculum.gap_fuzzy_topics import _unit
from bookgap.util import LOGGER, setup_logging

_MODULE = "artifacts_scripts.curriculum.gap_anchor_selection"


def _provenance() -> str:
    cmd = f"python -m {_MODULE} " + " ".join(shlex.quote(a) for a in sys.argv[1:])
    return ("\n\n---\n"
            f"*Generated by `{cmd}`*  \n"
            "*Regenerate with the command above; do not edit by hand.*\n")


def fl_anchors(E, masses, N, cand):
    """Greedy facility location: pick N anchors maximizing mass-weighted coverage
    F(S) = Σ_i mass_i · max_{a∈S} sim(i, a). A new anchor helps only where it
    covers under-covered works → naturally diverse. Returns indices into E."""
    Sc = E[cand] @ E.T                       # (M, n) candidate→all-work cosine
    n = E.shape[0]
    covered = np.full(n, -1.0)
    chosen, chosen_local = [], []
    for _ in range(min(N, len(cand))):
        gain = (masses[None, :] * np.maximum(0.0, Sc - covered[None, :])).sum(axis=1)
        gain[chosen_local] = -np.inf
        c = int(np.argmax(gain))
        chosen.append(int(cand[c])); chosen_local.append(c)
        covered = np.maximum(covered, Sc[c])
    return chosen


def dpp_anchors(E, masses, N, cand):
    """Greedy MAP-DPP (Chen et al. 2018 fast Cholesky): N high-quality (log1p mass)
    + mutually dissimilar (cosine kernel) anchors. Returns indices into E."""
    q = np.log1p(masses[cand])
    K = np.clip(E[cand] @ E[cand].T, 0.0, None)
    L = (q[:, None] * q[None, :]) * K
    M = L.shape[0]
    cis = np.zeros((N, M))
    di2s = np.diag(L).astype(np.float64).copy()
    selected = [int(np.argmax(di2s))]
    for i in range(1, N):
        j = selected[-1]
        ci_opt = cis[:i, j]
        di_opt = math.sqrt(max(di2s[j], 1e-12))
        eis = (L[j, :] - ci_opt @ cis[:i, :]) / di_opt
        cis[i, :] = eis
        di2s = di2s - eis ** 2
        di2s[j] = -np.inf
        nxt = int(np.argmax(di2s))
        if di2s[nxt] <= 1e-12:
            break
        selected.append(nxt)
    return [int(cand[s]) for s in selected]


def _metrics(A_unit, E, masses, redundant_thresh=0.7):
    """Redundancy (pairwise cosine among anchors) + mass-weighted coverage."""
    G = A_unit @ A_unit.T
    iu = np.triu_indices(len(A_unit), k=1)
    pair = G[iu]
    cover = float((masses * (E @ A_unit.T).max(axis=1)).sum() / masses.sum())
    return {
        "max_pair_cos": float(pair.max()) if pair.size else 0.0,
        "mean_top5_cos": float(np.sort(pair)[::-1][:5].mean()) if pair.size else 0.0,
        "n_pairs_over_thresh": int((pair > redundant_thresh).sum()),
        "coverage": cover,
    }


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--run-dir", required=True, type=Path)
    ap.add_argument("--field", default="17")
    ap.add_argument("--n", type=int, default=0, help="number of anchors (default: run's topic count)")
    ap.add_argument("--candidates", type=int, default=400, help="top-mass works considered as anchors")
    ap.add_argument("--redundant-thresh", type=float, default=0.7)
    ap.add_argument("--out", default=None, type=Path)
    args = ap.parse_args()
    setup_logging(log_name="anchor_selection", log_level="INFO", include_time=False)

    rd = args.run_dir
    cfg = OmegaConf.structured(CurriculumConfig())
    cfg.experiment.cloud.filter_pair.pre.field = str(args.field)
    cloud = instantiate(cfg.experiment.cloud)
    work_ids = cloud.work_ids()
    titles = cloud.work_titles()
    id2idx = {w: i for i, w in enumerate(work_ids)}

    fids = json.loads((rd / "filtered_work_ids.json").read_text())
    filt = np.array([id2idx[w] for w in fids], dtype=np.intp)
    E = _unit(np.asarray(cloud.embeddings(), dtype=np.float32)[filt])     # (n, d)
    masses = np.load(rd / "leaf_masses.npy").astype(np.float64)
    filt_titles = [titles[i] for i in filt]
    n = E.shape[0]
    pos = {w: i for i, w in enumerate(fids)}

    twi = json.loads((rd / "topic_work_ids.json").read_text())
    tkeys = sorted(twi, key=lambda k: int(k))
    ANCHOR_N = args.n or len(tkeys)

    # baseline: dendrogram topic centroids (mass-weighted mean of hard members)
    C = np.zeros((len(tkeys), E.shape[1]), dtype=np.float32)
    for ki, k in enumerate(tkeys):
        m = [pos[w] for w in twi[k] if w in pos]
        w = masses[m]
        C[ki] = np.average(E[m], axis=0, weights=w if w.sum() > 0 else None)
    C = _unit(C)

    cand = np.argsort(masses)[::-1][:args.candidates]
    fl = fl_anchors(E, masses, ANCHOR_N, cand)
    dpp = dpp_anchors(E, masses, ANCHOR_N, cand)

    sets = {
        "dendrogram": (C, None),
        "facility": (E[fl], fl),
        "dpp": (E[dpp], dpp),
    }
    lines = [f"# Topic-anchor selection probe — {rd.name}", "",
             f"{ANCHOR_N} anchors; candidates = top-{args.candidates} works by mass; "
             f"redundant pair = cosine > {args.redundant_thresh}.", "",
             "| method | max pair cos | mean top-5 pair cos | # redundant pairs | mass-wtd coverage |",
             "| :--- | :---: | :---: | :---: | :---: |"]
    for name, (A, _) in sets.items():
        m = _metrics(_unit(np.asarray(A, dtype=np.float32)), E, masses, args.redundant_thresh)
        lines.append(f"| {name} | {m['max_pair_cos']:.3f} | {m['mean_top5_cos']:.3f} | "
                     f"{m['n_pairs_over_thresh']} | {m['coverage']:.3f} |")
    lines += ["", "Lower redundancy (max/mean pair cosine, # redundant pairs) = more diverse "
              "anchors = fewer near-duplicate chapters; higher coverage = better spread.", ""]

    # Show the dendrogram's most-redundant anchor pair (the duplicate-chapter symptom).
    G = C @ C.T
    np.fill_diagonal(G, -1)
    i, j = np.unravel_index(int(np.argmax(G)), G.shape)
    def _lbl(twi_key):
        m = [pos[w] for w in twi[twi_key] if w in pos]
        return filt_titles[m[int(np.argmax(masses[m]))]][:70] if m else "(empty)"
    lines += [f"Most-redundant dendrogram anchor pair (cos {G[i, j]:.3f}): topic {tkeys[i]} "
              f"≈ topic {tkeys[j]}", f"- {tkeys[i]}: {_lbl(tkeys[i])}", f"- {tkeys[j]}: {_lbl(tkeys[j])}"]

    report = "\n".join(lines)
    print(report)
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(report + _provenance())
        print(f"\nwrote {args.out}")


if __name__ == "__main__":
    main()

"""Nonlinear keyword<->work fixed-point iteration — does it have seed-dependent basins?

Tests the co-clustering premise (docs/backlog/curriculum-keyword-coclustering.md): a
cluster = a self-consistent (works, keywords) pair. The loop alternates
  W2K: works -> distinctive keywords (log-lift vs the LOCAL pool background)
  K2W: keywords -> works (score pool works by keyword match), take top-M
from a seed. The keyword step is NONLINEAR (log-lift + top-k), which should create
seed-dependent fixed points (basins) where a linear power iteration mode-collapses to
one global attractor. Key question: run UNANCHORED — do different seeds converge to
DIFFERENT coherent clusters (basins exist) or the same (collapse)?

The pool = the run-dir's selected works (the gap's local neighborhood), which is also
the boundary-LOCAL background for the lift (vs the global corpus — the better ambient).
Phrases handled via one shared unigram+bigram vocabulary over the pool (the
vocabulary/frequency split that resolves the quantum_hall/hall_effect mismatch).

Example:
  python -m artifacts_scripts.curriculum.gap_keyword_iteration \\
      --run-dir artifacts/curriculum/neuromorphic_trackA_sem --field 17 \\
      --seed-chapters 5,11 --out docs/curriculum_eval_examples/neuromorphic_photonics/keyword_iteration.md
"""
from __future__ import annotations

import argparse
import json
import re
import shlex
import sys
from pathlib import Path

import numpy as np
from hydra.utils import instantiate
from omegaconf import OmegaConf

from artifacts_scripts.curriculum.config import CurriculumConfig
from bookgap.util import LOGGER, setup_logging

_MODULE = "artifacts_scripts.curriculum.gap_keyword_iteration"
_TOK = re.compile(r"[a-z0-9]+")
_STOP = set("the a an of and or to in for on with is are be by we our this that as at from using".split())


def _provenance() -> str:
    cmd = f"python -m {_MODULE} " + " ".join(shlex.quote(a) for a in sys.argv[1:])
    return f"\n\n---\n*Generated by `{cmd}`*  \n*Regenerate with the command above; do not edit by hand.*\n"


def _terms(text: str) -> set:
    t = [w for w in _TOK.findall(text.lower()) if w not in _STOP and len(w) > 2]
    return set(t) | {f"{t[i]}_{t[i+1]}" for i in range(len(t) - 1)}


def _jacc(a: set, b: set) -> float:
    return len(a & b) / len(a | b) if (a or b) else 1.0


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--run-dir", required=True, type=Path)
    ap.add_argument("--field", default="17")
    ap.add_argument("--seed-chapters", default="5,11", help="comma-separated topic ids to seed from")
    ap.add_argument("--top-k", type=int, default=25, help="keywords per W2K step")
    ap.add_argument("--top-m", type=int, default=120, help="works per K2W step")
    ap.add_argument("--iters", type=int, default=12)
    ap.add_argument("--anchor", action="store_true", help="keep the seed works in the set each step")
    ap.add_argument("--out", default=None, type=Path)
    args = ap.parse_args()
    setup_logging(log_name="kw_iter", log_level="INFO", include_time=False)

    cfg = OmegaConf.structured(CurriculumConfig())
    cfg.experiment.cloud.filter_pair.pre.field = str(args.field)
    cloud = instantiate(cfg.experiment.cloud)
    wid = cloud.work_ids(); id2idx = {w: i for i, w in enumerate(wid)}
    titles = cloud.work_titles(); abstracts = cloud.work_abstracts()

    fids = json.loads((args.run_dir / "filtered_work_ids.json").read_text())
    pool = [id2idx[w] for w in fids if w in id2idx]           # local pool (gap neighborhood)
    P = len(pool)
    doc_terms = [_terms(f"{titles[i]} {abstracts[i] or ''}") for i in pool]
    df = {}
    for s in doc_terms:
        for t in s:
            df[t] = df.get(t, 0) + 1
    inv = {}
    for d, s in enumerate(doc_terms):
        for t in s:
            inv.setdefault(t, []).append(d)
    eps = 0.5

    def w2k(S):  # works(set of pool-positions) -> {term: log-lift weight}, top-k
        nS = len(S)
        lifts = {}
        cnt = {}
        for d in S:
            for t in doc_terms[d]:
                cnt[t] = cnt.get(t, 0) + 1
        for t, c in cnt.items():
            pS = (c + eps) / (nS + eps)
            pP = (df[t] + eps) / (P + eps)
            lift = np.log(pS / pP)
            if lift > 0:
                lifts[t] = lift * np.log1p(c)               # favor distinctive AND recurrent
        return dict(sorted(lifts.items(), key=lambda x: -x[1])[: args.top_k])

    def k2w(kw):  # {term: weight} -> top-m pool positions by keyword-match score
        score = np.zeros(P)
        for t, wt in kw.items():
            for d in inv.get(t, []):
                score[d] += wt
        return set(np.argsort(score)[::-1][: args.top_m].tolist())

    twi = json.loads((args.run_dir / "topic_work_ids.json").read_text())
    pos = {w: d for d, w in enumerate(fids)}
    seeds = {}
    for ck in args.seed_chapters.split(","):
        seeds[ck] = {pos[w] for w in twi.get(ck.strip(), []) if w in pos}

    lines = [f"# Nonlinear keyword↔work iteration — {args.run_dir.name}", "",
             f"Pool: {P} works (local) · top_k={args.top_k} kw · top_m={args.top_m} works · "
             f"anchor={args.anchor}", ""]
    finals = {}
    for ck, seed in seeds.items():
        S = set(seed)
        traj = []
        for _ in range(args.iters):
            kw = w2k(S)
            Snew = k2w(kw)
            if args.anchor:
                Snew |= seed
            traj.append(_jacc(S, Snew))
            S = Snew
        finals[ck] = (S, w2k(S))
        kwlist = ", ".join(list(w2k(S))[:12])
        lines += [f"## seed = chapter {ck} (|seed|={len(seed)})",
                  f"- convergence (Jaccard step-to-step): {['%.2f' % j for j in traj]}",
                  f"- final |set|={len(S)}, drift-from-seed Jaccard={_jacc(set(seed), S):.2f}",
                  f"- final keywords: {kwlist}",
                  f"- top works: " + "; ".join(titles[pool[d]][:55] for d in list(S)[:3]), ""]
    sks = list(finals)
    if len(sks) >= 2:
        cross = _jacc(finals[sks[0]][0], finals[sks[1]][0])
        lines += [f"## Seed-dependence (basins?)",
                  f"Jaccard between fixed points of seed {sks[0]} vs {sks[1]}: **{cross:.2f}** "
                  f"(low = distinct basins = nonlinearity beat mode collapse; high = collapsed to one attractor)."]
    report = "\n".join(lines)
    print(report)
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(report + _provenance())
        print(f"\nwrote {args.out}")


if __name__ == "__main__":
    main()

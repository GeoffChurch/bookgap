"""Render the per-topic performance scatter as TikZ/pgfplots — the
figure called for at ``paper/main.tex:666`` ("a plot showing performance
in each of our 77 categories").

X-axis: target gap coverage (%).
Y-axis: proposal gap percentile (%).
One dot per topic with a successful proposal. The 6 known-failure topics
are labeled in red with clickable cross-refs into the per-topic appendix.

Output is a ``\\input``-able .tex containing a single ``figure``
environment. Text is real TeX (searchable, copyable).

Usage::

    uv run python -m artifacts_scripts.paper.per_topic_performance_scatter \\
        --run-dir outputs/gemma4_sweep/2026-05-22_11-11-43_gist_a10_b5_dropk10 \\
        --output  paper/artifacts/unused/per_topic_performance.tex
"""
from __future__ import annotations

import argparse
from pathlib import Path

from artifacts_scripts.common import latex_provenance, load_results_dataframe

# 6 known-failure topics (see §5.1 in the paper).
FAILURE_IDS = {
    "T10639", "T13674", "T10215", "T13623", "T14381", "T12157",
}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--run-dir", required=True, type=Path)
    ap.add_argument("--output", required=True, type=Path,
                    help="path to write the .tex figure")
    args = ap.parse_args()

    df = load_results_dataframe(args.run_dir)
    if df is None:
        raise SystemExit(
            f"No gaps_analysis_results.csv under {args.run_dir}"
        )
    # Keep one row per topic (headline runs are num_gaps=1; defensive
    # against historical multi-gap CSVs).
    df = df.drop_duplicates("topic_id", keep="first")

    # proposal_gap_size_percentile is undefined (NaN/empty) for topics
    # with 0 existing books — no empirical distribution to take a
    # percentile of. Surface those as "skipped" rather than plotting.
    has_pct = df["proposal_gap_size_percentile"].notna()
    skipped = df.loc[~has_pct, "topic_id"].tolist()
    df = df.loc[has_pct].copy()
    df["cov_pct"] = df["gap_coverage_fraction"] * 100.0
    df["pct_pct"] = df["proposal_gap_size_percentile"] * 100.0

    is_failure = df["topic_id"].isin(FAILURE_IDS)
    successes = list(zip(df.loc[~is_failure, "cov_pct"],
                         df.loc[~is_failure, "pct_pct"]))
    failures = list(zip(df.loc[is_failure, "cov_pct"],
                        df.loc[is_failure, "pct_pct"],
                        df.loc[is_failure, "topic_id"]))

    lines: list[str] = [
        "% Auto-generated by artifacts_scripts/paper/per_topic_performance_scatter.py",
        "% — do not edit by hand. Regenerate after a new sweep.",
        "\\begin{figure}[t]",
        "\\centering",
        "\\begin{tikzpicture}",
        "\\begin{axis}[",
        "  width=\\linewidth, height=0.62\\linewidth,",
        "  xlabel={Target gap coverage (\\%)},",
        "  ylabel={Proposal gap percentile (\\%)},",
        "  xmin=0, xmax=102, ymin=0, ymax=102,",
        "  xtick={0, 25, 50, 75, 100},",
        "  ytick={0, 25, 50, 75, 100},",
        "  grid=both,",
        "  major grid style={line width=.1pt, draw=gray!25},",
        "  tick label style={font=\\footnotesize},",
        "  label style={font=\\footnotesize},",
        "  axis line style={draw=gray!60},",
        "]",
        "% Successes: 69 topics that achieved good performance on at "
        "least one metric.",
        "\\addplot[only marks, mark=*, mark size=1.4pt,"
        " color=blue!50!black, opacity=0.7]",
        "  coordinates {",
    ]
    for x, y in successes:
        lines.append(f"    ({x:.2f}, {y:.2f})")
    lines.append("  };")

    # Failures: 6 topics with clickable cross-refs into the appendix.
    lines.extend([
        "% Failures: data-quality cases discussed in §5.1, labeled and "
        "linked into Appendix D.",
        "\\addplot[only marks, mark=*, mark size=2.4pt, color=red!75!black,",
        "         point meta=explicit symbolic,",
        "         nodes near coords,",
        "         every node near coord/.style={font=\\scriptsize\\ttfamily,"
        " anchor=west, xshift=2pt, color=red!60!black}]",
        "  coordinates {",
    ])
    for x, y, tid in failures:
        label = f"\\hyperref[appendix:proposal-{tid}]{{\\ttfamily {tid}}}"
        lines.append(f"    ({x:.2f}, {y:.2f}) [{{{label}}}]")
    lines.extend([
        "  };",
        "\\end{axis}",
        "\\end{tikzpicture}",
        "\\caption{Per-topic performance over all 75 topics with a successful "
        "proposal under the GIST+LPP+\\texttt{gemma4:31b} (10 articles, 5 books) run. "
        "Each blue dot is one topic, plotted at its target gap coverage "
        "and proposal gap percentile. The six topics labeled in red are "
        "the data-quality failures discussed in \\Cref{sec:overall_performance} "
        "(language-based or topic-misclassification clusters in the upstream "
        "OpenAlex index); each label is a hyperlink into the topic's "
        "detail page in \\Cref{appendix:per_topic_proposals}.}",
        "\\label{fig:per_topic_performance}",
        "\\end{figure}",
    ])

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines) + "\n" + latex_provenance(__spec__.name))
    print(f"Wrote {args.output}: {len(successes)} successes + "
          f"{len(failures)} labeled failures"
          + (f"; skipped {len(skipped)} ({', '.join(skipped)}) "
             f"with undefined percentile (no books in topic)"
             if skipped else ""))


if __name__ == "__main__":
    main()
